#: Primitive types whose values are already JSON-able as they come
# NOTE (mristin):
# A number is deliberately absent here. JSON can represent neither a non-finite
# floating-point number nor an integer outside ``[-2^53 + 1, 2^53 - 1]``, so
# a number has to be checked instead of being put into the mapping unchanged.
_PRIMITIVE_TYPES_SERIALIZED_AS_THEY_ARE = frozenset(
    [
        intermediate.PrimitiveType.BOOL,
        intermediate.PrimitiveType.STR,
    ]
)


_NUMBER_SERIALIZER_BY_PRIMITIVE_TYPE: Mapping[
    intermediate.PrimitiveType, Identifier
] = {
    intermediate.PrimitiveType.INT: Identifier("_int_to_jsonable"),
    intermediate.PrimitiveType.FLOAT: Identifier("_float_to_jsonable"),
}


def _serialized_as_it_is(type_annotation: intermediate.TypeAnnotationUnion) -> bool:
    """
    Check whether a value of the ``type_annotation`` is JSON-able as it comes.

    Such a value is put into the mapping unchanged, so it needs no serializer at all.
    A byte array is the only primitive which has to be encoded, and a constrained
    primitive is the primitive which it constrains.
    """
    primitive_type = intermediate.try_primitive_type(type_annotation)
    return (
        primitive_type is not None
        and primitive_type in _PRIMITIVE_TYPES_SERIALIZED_AS_THEY_ARE
    )


def _cls_serializer_name(cls: intermediate.ConcreteClass) -> Identifier:
    """Give out the name of the serializer of an instance of the ``cls``."""
    return python_naming.private_function_name(Identifier(f"{cls.name}_to_jsonable"))


def _list_serializer_name(
    type_annotation: intermediate.ListTypeAnnotation,
) -> Identifier:
    """Give out the name of the serializer of a list of the ``type_annotation``."""
    items_type_anno = intermediate.beneath_optional(type_annotation.items)

    return Identifier(
        f"_list_of__{python_common.atomic_moniker(items_type_anno)}_to_jsonable"
    )


def _tuple_serializer_name(
    type_annotation: intermediate.TupleTypeAnnotation,
) -> Identifier:
    """Give out the name of the serializer of a tuple of the ``type_annotation``."""
    monikers = [python_common.atomic_moniker(item) for item in type_annotation.items]

    return Identifier(
        f"_tuple{len(type_annotation.items)}_of__"
        + "__".join(monikers)
        + "_to_jsonable"
    )


def _generate_json_value_to_jsonable() -> Stripped:
    """Generate the function serializing a JSON-able value."""
    return Stripped(
        f'''\
def _json_value_to_jsonable(
{I}value: aas_types.JsonValue
) -> MutableJsonable:
{I}"""
{I}Serialize :paramref:`value` as a JSON-able structure.

{I}A JSON-able value is almost JSON-able as it comes, but not quite: its type
{I}rules out neither a ``None``, which the JSON ``null`` gives no
{I}representation for, nor an infinity and a not-a-number, which JSON can not
{I}represent at all, nor a non-string key in an object. Each is refused here,
{I}at any depth.

{I}The result is a new structure, and never :paramref:`value` itself, so that
{I}the serialized document does not alias the instance it came from.

{I}:param value: to be serialized
{I}:return: :paramref:`value`, as a JSON-able structure
{I}:raise: :py:class:`SerializationException` if :paramref:`value` is not JSON-able
{I}"""
{I}# NOTE (mristin):
{I}# A ``bool`` is an ``int`` in Python, so it has to be checked first --
{I}# otherwise every boolean would come out as a number.
{I}if isinstance(value, bool):
{II}return value

{I}if isinstance(value, int):
{II}# NOTE (mristin):
{II}# An ``int`` is written out as it stands. JSON knows a single
{II}# numeric type, though, so it has to be one which a ``float`` can
{II}# hold exactly -- otherwise a reader, which reads every number as
{II}# a ``float``, would get a different number back.
{II}if aas_common.try_to_convert_int_to_float(value) is None:
{III}raise SerializationException(
{IIII}f"Expected a JSON-able value, but got the integer {{value}}, "
{IIII}f"which is not exactly representable as a JSON number"
{III})

{II}return value

{I}if isinstance(value, float):
{II}if not math.isfinite(value):
{III}raise SerializationException(
{IIII}f"Expected a JSON-able value, but got the number {{value}}, "
{IIII}f"which is neither finite nor representable in JSON"
{III})

{II}return value

{I}if isinstance(value, str):
{II}return value

{I}if isinstance(value, (dict, collections.abc.Mapping)):
{II}mapping = dict()  # type: Dict[str, Any]
{II}for key, item_value in value.items():
{III}if not isinstance(key, str):
{IIII}raise SerializationException(
{IIIII}f"Expected only string keys in a JSON-able object, but got "
{IIIII}f"a key of type: {{type(key)}}"
{IIII})

{III}try:
{IIII}mapping[key] = _json_value_to_jsonable(item_value)
{III}except SerializationException as exception:
{IIII}exception._prepend_key(key)
{IIII}raise


{II}return mapping

{I}array_like = aas_common.try_to_cast_to_array_like(value)
{I}if array_like is not None:
{II}items = []  # type: List[Any]
{II}for i, item_value in enumerate(array_like):
{III}try:
{IIII}items.append(_json_value_to_jsonable(item_value))
{III}except SerializationException as exception:
{IIII}exception._prepend_index(i)
{IIII}raise

{II}return items

{I}raise SerializationException(
{II}f"Expected a JSON-able value (a boolean, a number, a string, an array "
{II}f"or an object), but got: {{type(value)}}"
{I})'''
    )


def _generate_atomic_serialization(
    access_expression: Stripped, type_anno: intermediate.AtomicTypeAnnotation
) -> Stripped:
    """
    Generate the serialization of the atomic value at the ``access_expression``.

    The ``access_expression`` should be a name, a member access or an index access,
    so that it can be suffixed without any parentheses.

    An instance is serialized by the function of its class, and the dispatch is left
    out wherever that class is already known, which it is for every class without
    concrete descendants. Only an abstract class, a concrete class with concrete
    descendants and a named union have to be dispatched on.

    A call is always broken at its argument, here and in
    :py:func:`_generate_serialization`, so that the generator needs no notion of
    columns. The name of a composed serializer is long enough that most of
    the calls have to be broken anyhow.
    """
    if _serialized_as_it_is(type_anno):
        return access_expression

    primitive_type = intermediate.try_primitive_type(type_anno)
    if primitive_type is not None:
        serializer_name = _NUMBER_SERIALIZER_BY_PRIMITIVE_TYPE.get(primitive_type, None)
        if serializer_name is None:
            assert primitive_type is intermediate.PrimitiveType.BYTEARRAY, (
                f"Expected all the other primitive types to be handled before, "
                f"but got: {primitive_type}"
            )
            serializer_name = Identifier("_bytes_to_base64_str")

        return Stripped(
            f"""\
{serializer_name}(
{I}{access_expression}
)"""
        )

    if isinstance(type_anno, intermediate.PrimitiveTypeAnnotation):
        raise AssertionError("Expected to handle this case before")

    elif isinstance(
        type_anno,
        (
            intermediate.JsonValueTypeAnnotation,
            intermediate.JsonArrayTypeAnnotation,
            intermediate.JsonObjectTypeAnnotation,
        ),
    ):
        # NOTE (mristin):
        # All three shapes are serialized by one function: an array and an
        # object are only JSON-able values whose top-level shape is already
        # known, and the function gives back whatever it is given.
        return Stripped(
            f"""\
_json_value_to_jsonable(
{I}{access_expression}
)"""
        )

    elif isinstance(type_anno, intermediate.OurTypeAnnotation):
        our_type = type_anno.our_type

        if isinstance(our_type, intermediate.Enumeration):
            return Stripped(f"{access_expression}.value")

        elif isinstance(our_type, intermediate.ConstrainedPrimitive):
            raise AssertionError("Expected to handle this case before")

        elif isinstance(our_type, intermediate.ConcreteClass):
            if len(our_type.concrete_descendants) == 0:
                serializer_name = _cls_serializer_name(our_type)

                return Stripped(
                    f"""\
{serializer_name}(
{I}{access_expression}
)"""
                )

            return Stripped(f"{access_expression}.transform(_SERIALIZER)")

        elif isinstance(
            our_type, (intermediate.AbstractClass, intermediate.NamedUnion)
        ):
            # NOTE (mristin):
            # A named union is dispatched on just like an abstract class. We keep it
            # as its own branch as we might want to support unions of primitives in
            # the future, at which point this branch would need to diverge.
            return Stripped(f"{access_expression}.transform(_SERIALIZER)")

        else:
            assert_never(our_type)

    else:
        assert_never(type_anno)


def _generate_serialization(
    access_expression: Stripped,
    type_anno: intermediate.TypeAnnotationExceptOptional,
) -> Stripped:
    """
    Generate the serialization of the value at the ``access_expression``.

    The ``type_anno`` is expected to be stripped of its optionality; the guard
    around the serialization is generated by the caller.

    Every serializer has the same shape, ``value 🠒 JSON-able value``. Unlike on
    the XML side, a JSON value is not framed by anything which encloses it, so
    the value at a key already is the whole value, and the serializers need no
    combinator tower: only a list and a tuple have to be composed at all.
    """
    if isinstance(type_anno, intermediate.AtomicTypeAnnotationAsTuple):
        return _generate_atomic_serialization(access_expression, type_anno)

    serializer_name: Identifier

    if isinstance(type_anno, intermediate.ListTypeAnnotation):
        items_type_anno = intermediate.beneath_optional(type_anno.items)

        # NOTE (mristin):
        # A list of the values which JSON carries as they come needs no serializer
        # of its own: ``list`` already is the whole conversion, and it copies at
        # the speed of C, whereas a composed serializer would cost a call and
        # a comprehension.
        if _serialized_as_it_is(items_type_anno):
            serializer_name = Identifier("list")
        else:
            serializer_name = _list_serializer_name(type_anno)

    elif isinstance(type_anno, intermediate.TupleTypeAnnotation):
        serializer_name = _tuple_serializer_name(type_anno)

    else:
        assert_never(type_anno)

    return Stripped(
        f"""\
{serializer_name}(
{I}{access_expression}
)"""
    )


class _SerializerRegistry:
    """
    Generate the code of the serializers which a meta-model needs to be composed.

    The composed serializers are de-duplicated by the type which they serialize, so
    that all the classes share them, and they are named by
    :py:func:`_list_serializer_name` and :py:func:`_tuple_serializer_name`. Nothing
    whatsoever is composed at the time of the serialization: a serializer is
    a module-level function, so the region contains no lambda at all.

    This is the mirror image of :py:class:`_ParserRegistry` of the reading side.

    The methods come grouped: first the queries, which give out what has been
    registered so far and change nothing, and then the commands, which register and
    give out nothing.
    """

    def __init__(self) -> None:
        """Initialize with nothing registered."""
        self._blocks_by_name = dict()  # type: MutableMapping[Identifier, Stripped]
        self._bytes_are_encoded = False
        self._checked_numbers = set()  # type: Set[intermediate.PrimitiveType]
        self._json_values_are_serialized = False

    @property
    def blocks(self) -> List[Stripped]:
        """Give out the code of the registered serializers, ordered by their name."""
        return [self._blocks_by_name[name] for name in sorted(self._blocks_by_name)]

    @property
    def bytes_are_encoded(self) -> bool:
        """Check whether a byte array is encoded anywhere in the meta-model."""
        return self._bytes_are_encoded

    @property
    def checked_numbers(self) -> AbstractSet[intermediate.PrimitiveType]:
        """Give out the number types which occur anywhere in the meta-model."""
        return self._checked_numbers

    @property
    def json_values_are_serialized(self) -> bool:
        """Check whether a JSON-able value occurs anywhere in the meta-model."""
        return self._json_values_are_serialized

    def note_bytes_are_encoded(self) -> None:
        """Note that a byte array is encoded somewhere in the meta-model."""
        self._bytes_are_encoded = True

    def note_json_values_are_serialized(self) -> None:
        """Note that a JSON-able value is serialized somewhere in the meta-model."""
        self._json_values_are_serialized = True

    def _add(self, name: Identifier, block: Stripped) -> None:
        """Register the ``block`` which defines the serializer ``name``."""
        self._blocks_by_name[name] = block

    def _register_list_serializer(
        self, type_annotation: intermediate.ListTypeAnnotation
    ) -> None:
        """Register the serializer of a list with items of the ``type_annotation``."""
        items_type_anno = intermediate.beneath_optional(type_annotation.items)

        assert not isinstance(
            items_type_anno,
            (intermediate.ListTypeAnnotation, intermediate.TupleTypeAnnotation),
        ), (
            "We chose to implement only a very limited pattern matching; "
            "see intermediate._translate._verify_only_simple_type_patterns"
        )

        # NOTE (mristin):
        # See the note in :py:func:`_generate_serialize_statement` on why such a list
        # is served by ``list`` instead of by a serializer of its own.
        if _serialized_as_it_is(items_type_anno):
            return

        self.register_serializer(items_type_anno)

        name = _list_serializer_name(type_annotation)

        list_type = python_common.generate_type(
            type_annotation, types_module=Identifier("aas_types")
        )

        item_serialization = _generate_atomic_serialization(
            Stripped("item"), items_type_anno
        )

        # NOTE (mristin):
        # A comprehension can not record which item was refused, so the items are
        # walked in a loop which knows the index. Every item is guarded, and not
        # only the one whose type we can see a refusal for today: nothing below
        # knows at which position the value sits, so a serializer which grows
        # a new way of failing would quietly lose the way to the culprit.
        body = Stripped(
            f"""\
jsonable = []  # type: List[MutableJsonable]
for i, item in enumerate(that):
{I}try:
{II}jsonable.append(
{III}{indent_but_first_line(item_serialization, III)}
{II})
{I}except SerializationException as exception:
{II}exception._prepend_index(i)
{II}raise
return jsonable"""
        )

        self._add(
            name,
            Stripped(
                f'''\
def {name}(
{I}that: {list_type}
) -> List[MutableJsonable]:
{I}"""
{I}Serialize :paramref:`that` as a list of
{I}{python_common.describe_atomic_type(items_type_anno)}.

{I}:param that: list to be serialized
{I}:return: JSON-able representation of :paramref:`that`
{I}"""
{I}{indent_but_first_line(body, I)}'''
            ),
        )

    def _register_tuple_serializer(
        self, type_annotation: intermediate.TupleTypeAnnotation
    ) -> None:
        """Register the serializer of a tuple with items of the ``type_annotation``."""
        item_expressions = []  # type: List[Stripped]

        for i, item_type_anno in enumerate(type_annotation.items):
            assert isinstance(
                item_type_anno, intermediate.AtomicTypeAnnotationAsTuple
            ), (
                "Tuple items are restricted to atomic types (primitives, constrained "
                "primitives, classes and enumerations) by "
                "intermediate._translate._verify_only_simple_type_patterns, so "
                "no nested optionals, lists or tuples are expected here."
            )

            self.register_serializer(item_type_anno)

            item_expressions.append(
                _generate_atomic_serialization(Stripped(f"that[{i}]"), item_type_anno)
            )

        name = _tuple_serializer_name(type_annotation)

        tuple_type = python_common.generate_type(
            type_annotation, types_module=Identifier("aas_types")
        )

        # NOTE (mristin):
        # A list literal can not record which item was refused, so the items are
        # appended one by one, each under its own position. Every item is guarded,
        # and not only the one whose type we can see a refusal for today: nothing
        # below knows at which position the value sits, so a serializer which grows
        # a new way of failing would quietly lose the way to the culprit.
        append_statements = []  # type: List[Stripped]

        for i, item_expression in enumerate(item_expressions):
            append_statements.append(
                Stripped(
                    f"""\
try:
{I}jsonable.append(
{II}{indent_but_first_line(item_expression, II)}
{I})
except SerializationException as exception:
{I}exception._prepend_index({i})
{I}raise"""
                )
            )

        joined_append_statements = "\n".join(append_statements)

        body = Stripped(
            f"""\
jsonable = []  # type: List[MutableJsonable]
{joined_append_statements}
return jsonable"""
        )

        self._add(
            name,
            Stripped(
                f'''\
def {name}(
{I}that: {indent_but_first_line(tuple_type, I)}
) -> List[MutableJsonable]:
{I}"""
{I}Serialize :paramref:`that` as a tuple of {len(type_annotation.items)} item(s).

{I}:param that: tuple to be serialized
{I}:return: JSON-able representation of :paramref:`that`
{I}"""
{I}{indent_but_first_line(body, I)}'''
            ),
        )

    def register_serializer(
        self, type_annotation: intermediate.TypeAnnotationUnion
    ) -> None:
        """
        Register the serializers needed to serialize a value of the ``type_annotation``.
        """
        type_anno = intermediate.beneath_optional(type_annotation)

        if _serialized_as_it_is(type_anno):
            return

        primitive_type = intermediate.try_primitive_type(type_anno)
        if primitive_type is not None:
            # NOTE (mristin):
            # A number is serialized by a module-level function which is emitted
            # unconditionally, so there is nothing to register for it.
            if primitive_type in _NUMBER_SERIALIZER_BY_PRIMITIVE_TYPE:
                self._checked_numbers.add(primitive_type)
                return

            assert primitive_type is intermediate.PrimitiveType.BYTEARRAY, (
                f"Expected all the other primitive types to be handled before, "
                f"but got: {primitive_type}"
            )

            self.note_bytes_are_encoded()
            return

        if isinstance(type_anno, intermediate.PrimitiveTypeAnnotation):
            raise AssertionError("Expected to handle this case before")

        elif isinstance(
            type_anno,
            (
                intermediate.JsonValueTypeAnnotation,
                intermediate.JsonArrayTypeAnnotation,
                intermediate.JsonObjectTypeAnnotation,
            ),
        ):
            self.note_json_values_are_serialized()

        elif isinstance(type_anno, intermediate.OurTypeAnnotation):
            # NOTE (mristin):
            # An enumeration is serialized by reading its ``value``, and an instance
            # by the function which is generated together with its class, so there is
            # nothing to register here.
            pass

        elif isinstance(type_anno, intermediate.ListTypeAnnotation):
            self._register_list_serializer(type_anno)

        elif isinstance(type_anno, intermediate.TupleTypeAnnotation):
            self._register_tuple_serializer(type_anno)

        else:
            assert_never(type_anno)


def _generate_serialization_exception() -> Stripped:
    """Generate the exception signalling that a value could not be serialized."""
    return Stripped(
        f'''\
class SerializationException(Exception):
{I}"""Signal that the JSON serialization could not be performed."""

{I}#: Human-readable explanation of the exception's cause
{I}cause: Final[str]

{I}def __init__(
{III}self,
{III}cause: str
{I}) -> None:
{II}"""Initialize with the given :paramref:`cause` and an empty path."""
{II}self.cause = cause
{II}self._segments = []  # type: List[str]

{I}@property
{I}def path(self) -> str:
{II}"""
{II}Render the path to the erroneous value as a Python access expression.

{II}The path points into the instance which you handed over for
{II}the serialization, and *not* into a JSON document -- at the point of
{II}the failure, there is no document yet. For example, ``.submodels[0].value``
{II}tells you that the serialization broke on ``that.submodels[0].value``.
{II}"""
{II}return ''.join(self._segments)

{I}def _prepend_property(self, name: str) -> None:
{II}"""Insert the access to the property :paramref:`name` before the path."""
{II}self._segments.insert(0, f'.{{name}}')

{I}def _prepend_index(self, index: int) -> None:
{II}"""Insert the access to the item at :paramref:`index` before the path."""
{II}self._segments.insert(0, f'[{{index}}]')

{I}def _prepend_key(self, key: str) -> None:
{II}"""
{II}Insert the access to the member :paramref:`key` before the path.

{II}Unlike a property of one of our classes, a member of an open JSON-able
{II}object is known only at run time and can be any string at all, so it is
{II}always rendered as a subscript.
{II}"""
{II}self._segments.insert(0, f'[{{key!r}}]')

{I}def __str__(self) -> str:
{II}if len(self._segments) == 0:
{III}return self.cause

{II}return f'{{self.path}}: {{self.cause}}\''''
    )


def _generate_number_serializers(
    checked_numbers: AbstractSet[intermediate.PrimitiveType],
) -> List[Stripped]:
    """
    Generate the serializers of the numbers which JSON can not represent.

    Only the serializers which are actually called are generated. A serializer
    which is not is not merely dead code: the one of a floating-point number
    needs :py:mod:`math`, which is imported only where a number occurs.
    """
    result = []  # type: List[Stripped]

    blocks = [
        Stripped(
            f'''\
def _int_to_jsonable(
{I}that: int
) -> int:
{I}"""
{I}Serialize :paramref:`that` integer to a JSON-able value.

{I}Only the integers in the range :math:`[-2^{{53}} + 1, 2^{{53}} - 1]` are
{I}serialized. Outside of it, an integer can not be exactly represented as
{I}a 64-bit floating-point number, which is what the JSON de-serializers of
{I}the other languages read a number into.

{I}:param that: integer to be serialized
{I}:return: :paramref:`that`, unchanged
{I}:raise: :py:class:`SerializationException` if outside the range
{I}"""
{I}if that < -9007199254740991 or that > 9007199254740991:
{II}raise SerializationException(
{III}f"The integer can not be serialized to JSON as it is outside "
{III}f"the range [-2^53 + 1, 2^53 - 1]: {{that}}"
{II})
{I}return that'''
        ),
        Stripped(
            f'''\
def _float_to_jsonable(
{I}that: float
) -> float:
{I}"""
{I}Serialize :paramref:`that` floating-point number to a JSON-able value.

{I}JSON knows neither an infinity nor a not-a-number, so we refuse to serialize
{I}them instead of leaving it to :py:mod:`json` to write them out as ``NaN``
{I}and ``Infinity``, which no conformant parser reads back.

{I}:param that: floating-point number to be serialized
{I}:return: :paramref:`that`, unchanged
{I}:raise: :py:class:`SerializationException` if not finite
{I}"""
{I}if not math.isfinite(that):
{II}raise SerializationException(
{III}f"JSON knows neither an infinity nor a not-a-number, so the value "
{III}f"can not be serialized: {{that}}"
{II})
{I}return that'''
        ),
    ]

    for primitive_type, block in zip(
        (intermediate.PrimitiveType.INT, intermediate.PrimitiveType.FLOAT), blocks
    ):
        if primitive_type in checked_numbers:
            result.append(block)

    return result


def _generate_cls_to_jsonable(cls: intermediate.ConcreteClass) -> Stripped:
    """Generate the function to serialize an instance of the ``cls``."""
    cls_name = python_naming.class_name(cls.name)
    function_name = _cls_serializer_name(cls)

    body_blocks = [
        Stripped("jsonable: MutableMapping[str, MutableJsonable] = dict()")
    ]  # type: List[Stripped]

    for prop in cls.properties:
        prop_name = python_naming.property_name(prop.name)

        key_literal = python_common.string_literal(prop.json_name)

        serialization = _generate_serialization(
            access_expression=Stripped(f"that.{prop_name}"),
            type_anno=intermediate.beneath_optional(prop.type_annotation),
        )

        statement = Stripped(f"jsonable[{key_literal}] = {serialization}")

        # NOTE (mristin):
        # Every property is guarded, and not only the one whose type we can see
        # a refusal for today. The property is recorded here, and nowhere below, as
        # nothing below knows through which property the value was reached, so
        # a serializer which grows a new way of failing would quietly lose the way
        # to the culprit.
        prop_name_literal = python_common.string_literal(prop.name)

        statement = Stripped(
            f"""\
try:
{I}{indent_but_first_line(statement, I)}
except SerializationException as exception:
{I}exception._prepend_property({prop_name_literal})
{I}raise"""
        )

        if isinstance(prop.type_annotation, intermediate.OptionalTypeAnnotation):
            statement = Stripped(
                f"""\
if that.{prop_name} is not None:
{I}{indent_but_first_line(statement, I)}"""
            )

        body_blocks.append(statement)

    if cls.serialization.with_model_type:
        model_type_literal = python_common.string_literal(
            naming.json_model_type(cls.name)
        )
        body_blocks.append(Stripped(f"jsonable['modelType'] = {model_type_literal}"))

    body_blocks.append(Stripped("return jsonable"))

    # NOTE (mristin):
    # The statements follow each other without a blank line in between, as they do in
    # the XML writers. The blank lines which used to separate them made up a quarter
    # of the region.
    body = "\n".join(body_blocks)

    return Stripped(
        f'''\
def {function_name}(
{I}that: aas_types.{cls_name}
) -> MutableMapping[str, MutableJsonable]:
{I}"""Serialize :paramref:`that` to a JSON-able representation."""
{I}{indent_but_first_line(body, I)}'''
    )


def _generate_serializer(symbol_table: intermediate.SymbolTable) -> Stripped:
    """Generate the transformer which dispatches on the class of an instance."""
    assignments = []  # type: List[Stripped]

    for our_type in symbol_table.our_types:
        if not isinstance(our_type, intermediate.ConcreteClass):
            continue

        method_name = python_naming.method_name(
            Identifier(f"transform_{our_type.name}")
        )
        serializer_name = _cls_serializer_name(our_type)

        assignments.append(
            Stripped(
                f"""\
{method_name} = staticmethod(
{I}{serializer_name}
)"""
            )
        )

    joined_assignments = "\n".join(assignments)

    return Stripped(
        f'''\
class _Serializer(
{II}aas_types.AbstractTransformer[MutableJsonable]
):
{I}"""
{I}Dispatch on the class of an instance to serialize it.

{I}The methods *are* the serializers, instead of forwarding to them, so that
{I}a dispatch costs a single call. Wherever the class of a value is already
{I}known -- which is every class without concrete descendants -- the serializer
{I}is called directly and this transformer is not involved at all.
{I}"""

{I}{indent_but_first_line(joined_assignments, I)}'''
    )


# endregion

# fmt: off
@ensure(lambda result: (result[0] is not None) ^ (result[1] is not None))
@ensure(
    lambda result:
    not (result[0] is not None) or result[0].endswith('\n'),
    "Trailing newline mandatory for valid end-of-files"
)
# fmt: on
def generate(
    symbol_table: intermediate.SymbolTable,
    qualified_module_name: python_common.QualifiedModuleName,
) -> Tuple[Optional[str], Optional[List[Error]]]:
    """
    Generate code for JSON de/serialization.

    The ``qualified_module_name`` indicates the fully-qualified name of the base module.
    """
    errors = python_common.errors_in_monikers(symbol_table)
    if len(errors) > 0:
        return None, errors

    # region Compose the de/serializers

    # NOTE (mristin):
    # We compose the de/serializers first so that we know which of them, and which of
    # the shared helpers, a meta-model actually reaches. Only those are finally
    # generated, gated along the call graph.

    registry = _ParserRegistry()
    serializer_registry = _SerializerRegistry()

    for concrete_cls in symbol_table.concrete_classes:
        for prop in concrete_cls.properties:
            registry.register_parser(prop.type_annotation)
            serializer_registry.register_serializer(prop.type_annotation)

    if len(symbol_table.concrete_classes) > 0 or len(symbol_table.named_unions) > 0:
        registry.note_needed_helper("_as_mapping")

    if any(len(cls.concrete_descendants) > 0 for cls in symbol_table.classes) or any(
        any(
            implementer.serialization.with_model_type
            for implementer in named_union.implementers
        )
        for named_union in symbol_table.named_unions
    ):
        registry.note_needed_helper("_dispatch_from_jsonable")

    helper_blocks = _generate_deserialization_helpers()

    needed_helpers = _collect_needed_helpers(registry.needed_helpers)

    # NOTE (mristin):
    # The :py:mod:`base64` module is imported only for the byte arrays, which are
    # the only values that JSON can not represent as they come.
    base64_import = (
        "import base64\n"
        if (
            "_bytes_from_jsonable" in needed_helpers
            or serializer_registry.bytes_are_encoded
        )
        else ""
    )

    # NOTE (mristin):
    # The :py:mod:`math` module is imported only for the numbers, to tell
    # an infinity and a not-a-number apart from what JSON can represent.
    math_import = (
        "import math\n"
        if (
            "_float_from_jsonable" in needed_helpers
            or intermediate.PrimitiveType.FLOAT in serializer_registry.checked_numbers
            or "_json_value_from_jsonable" in needed_helpers
            or serializer_registry.json_values_are_serialized
        )
        else ""
    )

    # endregion

    blocks = [
        Stripped(
            """\
\"\"\"
Provide de/serialization of AAS classes to/from JSON.

We can not use one-pass deserialization for JSON since the object
properties do not have fixed order, and hence we can not read
``modelType`` property ahead of the remaining properties.
\"\"\""""
        ),
        python_common.WARNING,
        Stripped(
            f"""\
{base64_import}\
import collections.abc
{math_import}\
import sys
from typing import (
{I}Any,
{I}Callable,
{I}Dict,
{I}Iterable,
{I}List,
{I}Mapping,
{I}MutableMapping,
{I}Optional,
{I}Sequence,
{I}Tuple,
{I}TypeVar,
{I}Union,
)

if sys.version_info >= (3, 8):
{I}from typing import Final
else:
{I}from typing_extensions import Final

import {qualified_module_name}.common as aas_common
import {qualified_module_name}.stringification as aas_stringification
import {qualified_module_name}.types as aas_types"""
        ),
        python_common.generate_note_on_the_three_error_paths(
            qualified_module_name=qualified_module_name
        ),
        Stripped(
            f"""\
class PropertySegment:
{I}\"\"\"Represent a property on a path to the erroneous value.\"\"\"

{I}#: Instance that contains the property
{I}instance: Final[Mapping[str, Any]]

{I}#: Name of the property
{I}name: Final[str]

{I}def __init__(
{III}self,
{III}instance: Mapping[str, Any],
{III}name: str
{I}) -> None:
{II}\"\"\"Initialize with the given values.\"\"\"
{II}self.instance = instance
{II}self.name = name"""
        ),
        Stripped(
            f"""\
class IndexSegment:
{I}\"\"\"Represent an index access on a path to the erroneous value.\"\"\"

{I}#: Container that contains the item
{I}container: Final[Iterable[Any]]

{I}#: Index of the item
{I}index: Final[int]

{I}def __init__(
{III}self,
{III}container: Iterable[Any],
{III}index: int
{I}) -> None:
{II}\"\"\"Initialize with the given values.\"\"\"
{II}self.container = container
{II}self.index = index"""
        ),
        Stripped(
            f"""\
class KeySegment:
{I}\"\"\"
{I}Represent a member access on a path to the erroneous value.

{I}Unlike a :py:class:`PropertySegment`, which names a property of one of our
{I}classes, a key names a member of an open JSON-able object. It is known only
{I}at run time, and can be any string at all, so it is always rendered
{I}as a subscript.
{I}\"\"\"

{I}#: Mapping that contains the value at :py:attr:`~key`
{I}mapping: Final[Mapping[str, Any]]

{I}#: Key of the value
{I}key: Final[str]

{I}def __init__(
{III}self,
{III}mapping: Mapping[str, Any],
{III}key: str
{I}) -> None:
{II}\"\"\"Initialize with the given values.\"\"\"
{II}self.mapping = mapping
{II}self.key = key"""
        ),
        Stripped(
            """\
Segment = Union[PropertySegment, IndexSegment, KeySegment]"""
        ),
        Stripped(
            f"""\
class Path:
{I}\"\"\"Represent the relative path to the erroneous value.\"\"\"

{I}def __init__(self) -> None:
{II}\"\"\"Initialize as an empty path.\"\"\"
{II}self._segments = []  # type: List[Segment]

{I}@property
{I}def segments(self) -> Sequence[Segment]:
{II}\"\"\"Get the segments of the path.\"\"\"
{II}return self._segments

{I}def _prepend(self, segment: Segment) -> None:
{II}\"\"\"Insert the :paramref:`segment` in front of other segments.\"\"\"
{II}self._segments.insert(0, segment)

{I}def __str__(self) -> str:
{II}if len(self._segments) == 0:
{III}return ""

{II}parts = []  # type: List[str]

{II}iterator = iter(self._segments)
{II}first = next(iterator)
{II}if isinstance(first, PropertySegment):
{III}parts.append(f"{{first.name}}")
{II}elif isinstance(first, IndexSegment):
{III}parts.append(f"[{{first.index}}]")
{II}elif isinstance(first, KeySegment):
{III}parts.append(f"[{{first.key!r}}]")
{II}else:
{III}aas_common.assert_never(first)

{II}for segment in iterator:
{III}if isinstance(segment, PropertySegment):
{IIII}parts.append(f".{{segment.name}}")
{III}elif isinstance(segment, IndexSegment):
{IIII}parts.append(f"[{{segment.index}}]")
{III}elif isinstance(segment, KeySegment):
{IIII}parts.append(f"[{{segment.key!r}}]")
{III}else:
{IIII}aas_common.assert_never(segment)

{II}return "".join(parts)"""
        ),
        Stripped(
            f"""\
class DeserializationException(Exception):
{I}\"\"\"Signal that the JSON de-serialization could not be performed.\"\"\"

{I}#: Human-readable explanation of the exception's cause
{I}cause: Final[str]

{I}#: Relative path to the erroneous value
{I}path: Final[Path]

{I}def __init__(
{III}self,
{III}cause: str
{I}) -> None:
{II}\"\"\"Initialize with the given :paramref:`cause` and an empty path.\"\"\"
{II}self.cause = cause
{II}self.path = Path()"""
        ),
        Stripped(
            f"""\
# NOTE (mristin):
# Recursive definitions are not yet available in mypy
# (see https://github.com/python/mypy/issues/731). We have to use ``Any``
# here, instead of recursive type annotations.
Jsonable = Union[
{I}bool,
{I}int,
{I}float,
{I}str,
{I}Sequence[Any],
{I}Mapping[str, Any]
]"""
        ),
        Stripped(
            f"""\
MutableJsonable = Union[
{I}bool,
{I}int,
{I}float,
{I}str,
{I}List[Any],
{I}MutableMapping[str, Any]
]"""
        ),
    ]  # type: List[Stripped]

    blocks.append(Stripped("# region De-serialization"))

    blocks.append(
        Stripped(
            f"""\
_ValueT = TypeVar("_ValueT")

#: Parse a JSON-able value into a value of the meta-model
_Parser = Callable[
{I}[Jsonable],
{I}_ValueT
]"""
        )
    )

    blocks.extend(
        block for name, block in helper_blocks.items() if name in needed_helpers
    )

    tuple_arities = registry.tuple_arities
    if len(tuple_arities) > 0:
        blocks.append(
            Stripped(
                "\n".join(
                    f'_TupleItem{i}T = TypeVar("_TupleItem{i}T")'
                    for i in range(1, max(tuple_arities) + 1)
                )
            )
        )
        for arity in sorted(tuple_arities):
            blocks.append(_generate_tuple_from_jsonable(arity=arity))

    blocks.extend(registry.blocks)

    for our_type in symbol_table.our_types:
        if isinstance(our_type, intermediate.Enumeration):
            blocks.append(_generate_enumeration_from_jsonable(enumeration=our_type))
        elif isinstance(our_type, intermediate.ConstrainedPrimitive):
            pass
        elif isinstance(our_type, intermediate.AbstractClass):
            blocks.append(_generate_dispatch_from_jsonable(cls=our_type))
        elif isinstance(our_type, intermediate.ConcreteClass):
            if len(our_type.concrete_descendants) > 0:
                blocks.append(_generate_dispatch_from_jsonable(cls=our_type))

            blocks.append(_generate_concrete_class_from_jsonable(cls=our_type))
        elif isinstance(our_type, intermediate.NamedUnion):
            blocks.append(_generate_named_union_from_jsonable(named_union=our_type))
        else:
            assert_never(our_type)

    # NOTE (mristin):
    # We add all the maps at the end as the functions might not have been defined yet
    # otherwise.
    for our_type in symbol_table.our_types:
        if isinstance(our_type, intermediate.AbstractClass):
            blocks.append(_generate_dispatch_map_for_abstract_class(cls=our_type))
        elif isinstance(our_type, intermediate.ConcreteClass):
            if len(our_type.concrete_descendants) > 0:
                blocks.append(_generate_dispatch_map_for_concrete_class(cls=our_type))
        elif isinstance(our_type, intermediate.NamedUnion):
            if any(
                implementer.serialization.with_model_type
                for implementer in our_type.implementers
            ):
                blocks.append(
                    _generate_dispatch_map_for_named_union(named_union=our_type)
                )

        else:
            pass

    blocks.append(Stripped("# endregion"))

    blocks.append(Stripped("# region Serialization"))

    blocks.append(_generate_serialization_exception())

    blocks.extend(_generate_number_serializers(serializer_registry.checked_numbers))

    if serializer_registry.json_values_are_serialized:
        blocks.append(_generate_json_value_to_jsonable())

    if serializer_registry.bytes_are_encoded:
        blocks.append(_generate_bytes_to_base64_str())

    blocks.extend(serializer_registry.blocks)

    for our_type in symbol_table.our_types:
        if not isinstance(our_type, intermediate.ConcreteClass):
            continue

        blocks.append(_generate_cls_to_jsonable(cls=our_type))
    blocks.append(_generate_serializer(symbol_table=symbol_table))

    blocks.append(Stripped("_SERIALIZER = _Serializer()"))

    blocks.append(
        Stripped(
            f"""\
def to_jsonable(that: aas_types.Class) -> MutableJsonable:
{I}\"\"\"
{I}Convert :paramref:`that` to a JSON-able structure.

{I}:param that:
{II}AAS data to be recursively converted to a JSON-able structure
{I}:return:
{II}JSON-able structure which can be further encoded with, *e.g.*, :py:mod:`json`
{I}:raise:
{II}:py:class:`SerializationException` if :paramref:`that` contains a number
{II}which JSON can not represent
{I}\"\"\"
{I}return that.transform(_SERIALIZER)"""
        )
    )

    blocks.append(Stripped("# endregion"))

    if len(errors) > 0:
        return None, errors

    blocks.append(python_common.WARNING)

    writer = io.StringIO()
    for i, block in enumerate(blocks):
        if i > 0:
            writer.write("\n\n\n")

        writer.write(block)

    writer.write("\n")

    return writer.getvalue(), None


