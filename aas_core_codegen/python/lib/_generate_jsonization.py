def _generate_named_union_from_jsonable(
    named_union: intermediate.NamedUnion,
) -> Stripped:
    """
    Generate the de-serialization dispatch for the named union.

    We dispatch on ``modelType`` for every implementer which sets it, and fall
    back to testing which implementer's required properties are all present
    for the remaining implementers. This mirrors the per-implementer
    partitioning already verified in the intermediate representation, so
    every implementer is covered by exactly one of the two strategies.
    """
    function_name = python_naming.function_name(
        Identifier(f"{named_union.name}_from_jsonable")
    )

    union_name = python_naming.union_name(named_union.name)

    with_model_type = [
        implementer
        for implementer in named_union.implementers
        if implementer.serialization.with_model_type
    ]
    without_model_type = [
        implementer
        for implementer in named_union.implementers
        if not implementer.serialization.with_model_type
    ]

    blocks = [Stripped("mapping = _as_mapping(jsonable)")]  # type: List[Stripped]

    if len(with_model_type) > 0:
        mapping_name = python_naming.private_constant_name(
            Identifier(f"{named_union.name}_from_jsonable_dispatch")
        )

        blocks.append(
            Stripped(
                f"""\
if "modelType" in mapping:
{I}return _dispatch_from_jsonable(
{II}mapping,
{II}{mapping_name},
{II}{python_common.string_literal(union_name)}
{I})"""
            )
        )

    for implementer in without_model_type:
        required_json_names = [
            implementer.properties_by_name[arg.name].json_name
            for arg in implementer.constructor.arguments
            if not isinstance(arg.type_annotation, intermediate.OptionalTypeAnnotation)
        ]
        assert len(required_json_names) > 0, (
            f"Expected the structurally-dispatched implementer "
            f"{implementer.name!r} of the named union {named_union.name!r} "
            f"to have at least one required property; this should have "
            f"already been verified in the intermediate representation."
        )

        implementer_function = python_naming.function_name(
            Identifier(f"{implementer.name}_from_jsonable")
        )

        conditions = [
            f"{python_common.string_literal(json_name)} in mapping"
            for json_name in required_json_names
        ]

        one_liner = f"if {' and '.join(conditions)}:"
        if len(one_liner) <= 70:
            if_stmt = Stripped(one_liner)
        else:
            joined_conditions = f"\n{II}and ".join(conditions)
            if_stmt = Stripped(
                f"""\
if (
{II}{joined_conditions}
):"""
            )

        blocks.append(
            Stripped(
                f"""\
{if_stmt}
{I}return {implementer_function}(mapping)"""
            )
        )

    blocks.append(
        Stripped(
            f"""\
raise DeserializationException(
{I}"Could not determine the concrete type of {union_name} "
{I}"for the given JSON object"
)"""
        )
    )

    writer = io.StringIO()
    writer.write(
        f"""\
def {function_name}(
{II}jsonable: Jsonable
) -> aas_types.{union_name}:
{I}\"\"\"
{I}Parse an instance of :py:class:`.types.{union_name}` from the JSON-able
{I}structure :paramref:`jsonable`.

{I}:param jsonable: structure to be parsed
{I}:return: Concrete instance corresponding to :py:class:`.types.{union_name}`
{I}:raise: :py:class:`DeserializationException` if unexpected :paramref:`jsonable`
{I}\"\"\"
"""
    )

    for i, block in enumerate(blocks):
        if i > 0:
            writer.write("\n\n")
        writer.write(textwrap.indent(block, I))

    return Stripped(writer.getvalue())


def _generate_optional_type(
    type_annotation: intermediate.TypeAnnotationUnion,
) -> Stripped:
    """
    Generate the type of the local variable which holds a parsed property.

    A property is unset until we parse it, so the variable is optional regardless
    of whether the property itself is.
    """
    prop_type = python_common.generate_type(
        type_annotation, types_module=Identifier("aas_types")
    )

    if isinstance(type_annotation, intermediate.OptionalTypeAnnotation):
        return prop_type

    if "\n" not in prop_type:
        return Stripped(f"Optional[{prop_type}]")

    # NOTE (mristin):
    # ``prop_type`` is already broken over multiple lines (see, *e.g.*, the
    # ``TupleTypeAnnotation`` case in :py:func:`python_common.generate_type`), so we
    # follow the same bracket-per-line style here instead of squeezing it onto
    # one line.
    return Stripped(
        f"""\
Optional[
{I}{indent_but_first_line(prop_type, I)}
]"""
    )


def _generate_concrete_class_from_jsonable(
    cls: intermediate.ConcreteClass,
) -> Stripped:
    """
    Generate the deserialization function for a concrete class.

    This function performs no dispatch. If it de-serializes a concrete class with
    concrete descendants, we have to provide a different name. Otherwise, it would
    shadow the name for the dispatch function.
    """
    # fmt: off
    assert (
            sorted(
                (arg.name, str(arg.type_annotation))
                for arg in cls.constructor.arguments
            ) == sorted(
                (prop.name, str(prop.type_annotation))
                for prop in cls.properties
            )
    ), (
        "(mristin, 2022-10-03) We assume that the properties and constructor arguments "
        "are identical at this point. If this is not the case, we have to re-write the "
        "logic substantially! Please contact the developers if you see this."
    )
    # fmt: on

    cls_name = python_naming.class_name(cls.name)

    # NOTE (mristin):
    # If the class has no concrete descendants, this function is the sole entry
    # point for the de-serialization. In that case, we have to explicitly check the
    # ``modelType`` — for cases where the serialization rules impose a model type
    # for backwards compatibility even though it is redundant.
    #
    # If the class has concrete descendants, we can only publicly de-serialize it
    # through a dispatching function, which has innately checked the model type, so
    # we do not have to repeat the check here.
    checks_model_type = (
        len(cls.concrete_descendants) == 0 and cls.serialization.with_model_type
    )

    blocks = [Stripped("mapping = _as_mapping(jsonable)")]  # type: List[Stripped]

    # NOTE (mristin):
    # We check the model type up front, before we parse any of the properties, so
    # that a wrong one is reported as such instead of as whatever the properties of
    # the wrong class happen to break on first.
    #
    # We compare it as it came on the wire. That rejects a value of the wrong type
    # just as well as parsing it would, and it costs no call. An absent model type
    # is ``None`` and fails the very same comparison.
    if checks_model_type:
        model_type_literal = python_common.string_literal(
            naming.json_model_type(cls.name)
        )

        blocks.append(
            Stripped(
                f"""\
model_type = mapping.get('modelType', None)
if model_type != {model_type_literal}:
{I}raise DeserializationException(
{II}f"Expected modelType to be {model_type_literal}, "
{II}f"but got: {{model_type!r}}"
{I})"""
            )
        )

    # region Declare a local for every property, so that the constructor call is
    # type-checked

    variable_by_prop_name = dict()  # type: MutableMapping[Identifier, Identifier]

    declarations = []  # type: List[Stripped]

    for prop in cls.properties:
        variable = python_naming.variable_name(Identifier(f"the_{prop.name}"))
        variable_by_prop_name[prop.name] = variable

        declarations.append(
            Stripped(
                f"{variable}: {_generate_optional_type(prop.type_annotation)} = None"
            )
        )

    if len(declarations) > 0:
        blocks.append(Stripped("\n".join(declarations)))

    # endregion

    # region Switch on the property name

    # NOTE (mristin):
    # The model type comes first. It is on the wire for every instance of a class
    # which carries one, while any other property may or may not be there, so it is
    # the branch most often taken. It has been dealt with before the loop -- either
    # above, or by the dispatch which got us here -- so we only have to accept it.
    branches = []  # type: List[Stripped]

    if checks_model_type:
        model_type_note = "# The model type has already been checked above."
    elif len(cls.concrete_descendants) > 0:
        model_type_note = "# The dispatch has already matched the model type."
    else:
        model_type_note = (
            "# The model type is redundant for this class, and we simply accept it."
        )

    branches.append(
        Stripped(
            f"""\
{model_type_note}
pass"""
        )
    )

    keys = [Stripped("'modelType'")]  # type: List[Stripped]

    for prop in cls.properties:
        keys.append(python_common.string_literal(prop.json_name))

        variable = variable_by_prop_name[prop.name]
        parser = _parser_name(prop.type_annotation)

        one_liner = f"{variable} = {parser}(jsonable_value)"

        # NOTE (mristin):
        # The assignment lives three levels in, so we have to break it over
        # multiple lines as soon as it does not fit.
        if len(III) + len(one_liner) <= 88:
            branches.append(Stripped(one_liner))
        else:
            branches.append(
                Stripped(
                    f"""\
{variable} = (
{I}{parser}(jsonable_value)
)"""
                )
            )

    switch_writer = io.StringIO()
    for i, (key, branch) in enumerate(zip(keys, branches)):
        keyword = "if" if i == 0 else "elif"
        switch_writer.write(
            f"""\
{II}{keyword} key == {key}:
{III}{indent_but_first_line(branch, III)}
"""
        )

    switch_writer.write(
        f"""\
{II}else:
{III}raise DeserializationException(
{IIII}f"Unexpected property: {{key}}"
{III})"""
    )

    # NOTE (mristin):
    # The property is marked on the error path here, once for all the properties,
    # instead of in every branch: ``key`` *is* the JSON name of the property which
    # we are parsing. We wrap the loop rather than its body, as the two are
    # equivalent -- ``key`` still holds the culprit -- and the enclosing form is
    # cheaper on the Python versions which do not have a zero-cost ``try``.
    iteration = (
        "for key, jsonable_value in mapping.items():"
        if len(cls.properties) > 0
        else "for key in mapping:"
    )

    blocks.append(
        Stripped(
            f"""\
try:
{I}{iteration}
{switch_writer.getvalue()}
except DeserializationException as exception:
{I}exception.path._prepend(
{II}PropertySegment(mapping, key)
{I})
{I}raise"""
        )
    )

    # endregion

    # region Check the required properties

    for prop in cls.properties:
        if isinstance(prop.type_annotation, intermediate.OptionalTypeAnnotation):
            continue

        cause_literal = python_common.string_literal(
            f"The required property {prop.json_name!r} is missing"
        )

        blocks.append(
            Stripped(
                f"""\
if {variable_by_prop_name[prop.name]} is None:
{I}raise DeserializationException(
{II}{cause_literal}
{I})"""
            )
        )

    # endregion

    # region Pass in the arguments to the constructor

    if len(cls.constructor.arguments) == 0:
        blocks.append(Stripped(f"return aas_types.{cls_name}()"))
    else:
        init_writer = io.StringIO()
        init_writer.write(f"return aas_types.{cls_name}(\n")

        for i, arg in enumerate(cls.constructor.arguments):
            init_writer.write(f"{I}{variable_by_prop_name[arg.name]}")

            if i < len(cls.constructor.arguments) - 1:
                init_writer.write(",\n")
            else:
                init_writer.write("\n")

        init_writer.write(")")

        blocks.append(Stripped(init_writer.getvalue()))

    # endregion

    writer = io.StringIO()

    if len(cls.concrete_descendants) == 0:
        function_name = python_naming.function_name(
            Identifier(f"{cls.name}_from_jsonable")
        )
    else:
        function_name = python_naming.function_name(
            Identifier(f"_{cls.name}_from_jsonable_without_dispatch")
        )

    docstring_blocks = [
        Stripped(
            f"""\
Parse an instance of :py:class:`.types.{cls_name}` from the JSON-able
structure :paramref:`jsonable`."""
        )
    ]  # type: List[Stripped]

    if len(cls.concrete_descendants) > 0:
        function_name_with_dispatch = python_naming.function_name(
            Identifier(f"{cls.name}_from_jsonable")
        )

        docstring_blocks.append(
            Stripped(
                f"""\
This function performs no dispatch! It is used to parse the properties
as-are, and already assumes the exact model type. Usually, this function
is called from within a dispatching function, and you never call it
directly. If you want to de-serialize an instance of
:py:class:`.types.{cls_name}`, call
:py:func:`{function_name_with_dispatch}`."""
            )
        )

    docstring_blocks.append(
        Stripped(
            f"""\
:param jsonable: structure to be parsed
:return: Parsed instance of :py:class:`.types.{cls_name}`
:raise: :py:class:`DeserializationException` if unexpected :paramref:`jsonable`"""
        )
    )

    docstring = "\n\n".join(docstring_blocks)

    writer.write(
        f"""\
def {function_name}(
{II}jsonable: Jsonable
) -> aas_types.{cls_name}:
{I}\"\"\"
{I}{indent_but_first_line(docstring, I)}
{I}\"\"\"
"""
    )

    for i, block in enumerate(blocks):
        if i > 0:
            writer.write("\n\n")
        writer.write(textwrap.indent(block, I))

    return Stripped(writer.getvalue())


