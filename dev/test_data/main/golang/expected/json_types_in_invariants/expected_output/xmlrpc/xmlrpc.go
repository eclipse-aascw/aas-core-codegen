// Read the content of the discriminator element named `local`.
func readValueByLocal(
	decoder *xml.Decoder,
	current xml.Token,
	local string,
) (value aastypes.JsonValue, next xml.Token, err error) {
	switch local {
		case "boolean":
			value, next, err = readBoolean(decoder, current)
		case "double":
			value, next, err = readDouble(decoder, current)
		case "string":
			var text string
			text, next, err = xmlcommon.ReadText(decoder, current)
			// NOTE (mristin):
			// `xs:string` is `preserve` and not `collapse`, so a `<string>` keeps
			// its whitespace, unlike a `<boolean>` or a `<double>`.
			value = text
		case "array":
			var items aastypes.JsonArray
			items, next, err = ReadArrayContent(decoder, current)
			value = items
		case "struct":
			var members aastypes.JsonObject
			members, next, err = ReadObjectContent(decoder, current)
			value = members
		default:
			// NOTE (mristin):
			// No element has been entered which could be a step of the path: it is
			// this very element which does not belong here.
			err = xmlcommon.NewDeserializationError(
				fmt.Sprintf(
					"Expected a discriminator element (one of boolean, double, "+
					"string, array or struct), but got: %s",
					local,
				),
			)
			return
	}

	if err != nil {
		xmlcommon.MustDeserializationError(err).PrependName(local)
	}
	return
}

// Read the content of a `<boolean>` element.
//
// Real XML-RPC tooling writes and expects a strict `1`/`0`, and not
// the `true`/`false` which `xs:boolean` and the rest of this module use.
func readBoolean(
	decoder *xml.Decoder,
	current xml.Token,
) (value aastypes.JsonValue, next xml.Token, err error) {
	var text string
	text, next, err = xmlcommon.ReadText(decoder, current)
	if err != nil {
		return
	}

	// NOTE (mristin):
	// `whiteSpace` is fixed to `collapse` for every atomic XSD type but
	// a string, so a pretty-printed `<boolean>` has to be read as well.
	text = xmlcommon.CollapseWhitespace(text)

	switch text {
		case "1":
			value = true
		case "0":
			value = false
		default:
			err = xmlcommon.NewDeserializationError(
				fmt.Sprintf(
					"Expected \"0\" or \"1\" as the text of a boolean element, "+
					"but got: %s",
					text,
				),
			)
	}
	return
}

// Read the content of a `<double>` element.
func readDouble(
	decoder *xml.Decoder,
	current xml.Token,
) (value aastypes.JsonValue, next xml.Token, err error) {
	var text string
	text, next, err = xmlcommon.ReadText(decoder, current)
	if err != nil {
		return
	}

	// NOTE (mristin):
	// See the note in readBoolean on why the whitespace is collapsed.
	text = xmlcommon.CollapseWhitespace(text)

	// NOTE (mristin):
	// The lexical form is matched before the text is converted.
	// strconv.ParseFloat reads more than we admit here: a hexadecimal
	// literal, an underscore separator, and the spellings "inf",
	// "infinity" and "nan".
	//
	// Mind that the numeral excludes "INF", "-INF" and "NaN" on purpose,
	// unlike xs:double, which names all three. A double element carries
	// a JSON number, and JSON knows neither an infinity nor
	// a not-a-number, so there is no JSON-able value for such a text
	// to de-serialize into.
	if !doubleRe.MatchString(text) {
		err = xmlcommon.NewDeserializationError(
			fmt.Sprintf(
				"Expected a number as the text of a double element, but got: %s",
				text,
			),
		)
		return
	}

	var number float64
	number, err = strconv.ParseFloat(text, 64)
	if err != nil || math.IsInf(number, 0) {
		// NOTE (mristin):
		// A literal too large for a float64 gives an infinity, which is no
		// JSON-able value either, so it is refused rather than rounded.
		err = xmlcommon.NewDeserializationError(
			fmt.Sprintf(
				"Expected a number representable as a JSON-able value as the "+
				"text of a double element, but got: %s",
				text,
			),
		)
		return
	}

	value = number
	return
}

