func writeObjectContent(
	encoder *xml.Encoder,
	value aastypes.JsonObject,
	undeclareNamespace bool,
) (err error) {
	// NOTE (mristin):
	// The keys are sorted so that the same object always gives the same
	// document, as the iteration order of a Go map is deliberately random.
	keys := make([]string, 0, len(value))
	for key := range value {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	for _, key := range keys {
		err = xmlcommon.WriteStartElementInNoNamespace(encoder, "member", undeclareNamespace)
		if err != nil {
			return
		}

		err = xmlcommon.WriteElement(encoder, "name", key, xmlcommon.WriteAsText_string)
		if err != nil {
			return
		}

		err = xmlcommon.WriteElement(encoder, "value", value[key], writeNestedValueContent)
		if err != nil {
			xmlcommon.MustSerializationError(err).PrependKey(key)
			return
		}

		err = xmlcommon.WriteEndElement(encoder, "member", false)
		if err != nil {
			return
		}
	}
	return
}

