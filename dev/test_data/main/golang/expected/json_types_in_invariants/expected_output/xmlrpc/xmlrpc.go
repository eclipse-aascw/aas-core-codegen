// Read the content of the `<data>` element of a JSON-able array.
func readData(
	decoder *xml.Decoder,
	current xml.Token,
	local string,
) (value aastypes.JsonArray, next xml.Token, err error) {
	if local != "data" {
		err = xmlcommon.NewDeserializationError(
			fmt.Sprintf(
				"Expected a data element in a JSON-able array, but got: %s",
				local,
			),
		)
		return
	}

	// NOTE (mristin):
	// An empty data element gives an empty array, and not a nil one, so
	// that the value round-trips as the empty array it was.
	value = aastypes.JsonArray{}

	next = current
	for {
		next, err = xmlcommon.SkipEmptyTextWhitespaceAndComments(decoder, next)
		if err != nil {
			return
		}

		if _, ok := next.(xml.StartElement); !ok {
			break
		}

		var item aastypes.JsonValue
		item, next, err = xmlcommon.ReadElementDispatchedInNoNamespace(
			decoder, next, readArrayItem,
		)
		if err != nil {
			// NOTE (mristin):
			// Every item of a `<data>` element is a `<value>` element, so the index
			// already names the element which was entered, and there is no step of
			// its own for it.
			xmlcommon.MustDeserializationError(err).
				PrependIndex(len(value)).
				PrependName("data")
			return
		}

		value = append(value, item)
	}
	return
}

