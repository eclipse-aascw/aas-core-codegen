func writeValueContent(
	encoder *xml.Encoder,
	value aastypes.JsonValue,
	undeclareNamespace bool,
) (err error) {
	if value == nil {
		err = xmlcommon.NewSerializationError(
			"Expected a JSON-able value, but got a nil",
		)
		return
	}

	switch casted := value.(type) {
		case bool:
			// NOTE (mristin):
			// Real XML-RPC tooling writes and expects a strict `1`/`0`, and not
			// the `true`/`false` which `xs:boolean` and the rest of this module
			// use.
			text := "0"
			if casted {
				text = "1"
			}
			err = xmlcommon.WriteElementInNoNamespace(
				encoder, "boolean", undeclareNamespace,
				text,
				func(anEncoder *xml.Encoder, aValue string) error {
					return xmlcommon.WriteText(anEncoder, aValue)
				},
			)
			return

		case float64:
			// NOTE (mristin):
			// JSON knows neither an infinity nor a not-a-number, so neither is
			// a JSON-able value, and readDouble refuses to read either
			// back.
			if math.IsInf(casted, 0) || math.IsNaN(casted) {
				err = xmlcommon.NewSerializationError(
					fmt.Sprintf(
						"Expected a JSON-able value, but got the number %v, which "+
						"is neither finite nor representable in JSON",
						casted,
					),
				)
				return
			}
			err = xmlcommon.WriteElementInNoNamespace(
				encoder, "double", undeclareNamespace,
				casted,
				xmlcommon.WriteAsText_double,
			)
			return

		case string:
			err = xmlcommon.WriteElementInNoNamespace(
				encoder, "string", undeclareNamespace,
				casted,
				xmlcommon.WriteAsText_string,
			)
			return

		case aastypes.JsonArray:
			err = xmlcommon.WriteElementInNoNamespace(
				encoder, "array", undeclareNamespace,
				casted,
				writeNestedArrayContent,
			)
			return

		case aastypes.JsonObject:
			err = xmlcommon.WriteElementInNoNamespace(
				encoder, "struct", undeclareNamespace,
				casted,
				writeNestedObjectContent,
			)
			return

		default:
			err = xmlcommon.NewSerializationError(
				fmt.Sprintf(
					"Expected a JSON-able value (a bool, a float64, a string, "+
					"a JsonArray or a JsonObject), but got: %T",
					value,
				),
			)
			return
	}
}

