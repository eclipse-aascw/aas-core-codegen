/**
 * Match a numeral of the `<double>` lexical space.
 *
 * @remarks
 * This is the numeric part of the lexical space of `xs:double`, and
 * deliberately not its three named literals -- `INF`, `-INF` and `NaN` --
 * since a JSON number can be none of them.
 */
const DOUBLE_RE = new RegExp(
  "^(\\+|-)?([0-9]+(\\.[0-9]*)?|\\.[0-9]+)([Ee](\\+|-)?[0-9]+)?$"
);

/**
 * Parse the content of an element holding a JSON-able value.
 *
 * @remarks
 * The content is a single discriminator element -- `<boolean>`, `<double>`,
 * `<string>`, `<array>` or `<struct>` -- which says what the value is.
 *
 * @param cursor - to read from
 * @returns parsed JSON-able value, or an error
 */
export function parseValueContent(
  cursor: XmlCursor
): AasCommon.Either<AasTypes.JsonValue, DeserializationError> {
  const startTagOrError = readNextOpenTagInNoNamespace(cursor);
  if (startTagOrError.error !== null) {
    return new AasCommon.Either<AasTypes.JsonValue, DeserializationError>(
      null, startTagOrError.error
    );
  }

  const localName = localNameOfTag(startTagOrError.mustValue().tag);

  const parseContent = parserForDiscriminator(localName);
  if (parseContent === null) {
    // NOTE (mristin):
    // The element which is no discriminator at all gets no step of its own:
    // it is that very element which does not belong here, so naming it in
    // the path as well as in the message would say nothing more.
    return newDeserializationError<AasTypes.JsonValue>(
      `Expected a discriminator element (one of 'boolean', 'double', ` +
        `'string', 'array' or 'struct'), but got: '${localName}'`
    );
  }

  cursor.advance();

  const parsed = parseElementContentInNoNamespace(cursor, localName, parseContent);
  if (parsed.error !== null) {
    // NOTE (mristin):
    // The discriminator is an element which we actually enter, so it is
    // a step of the path.
    parsed.error.path.prepend(new ElementSegment(localName));
  }

  return parsed;
}

/**
 * Give out the parser of the content of the discriminator `localName`.
 *
 * @param localName - local name of the discriminator element
 * @returns the parser of its content, or `null` if `localName` names no
 * discriminator
 */
function parserForDiscriminator(
  localName: string
): ContentParser<AasTypes.JsonValue> | null {
  switch (localName) {
    case "boolean":
      return parseBooleanContent;
    case "double":
      return parseDoubleContent;
    case "string":
      return parseStringContent;
    case "array":
      return parseArrayBody;
    case "struct":
      return parseStructBody;
    default:
      return null;
  }
}

/**
 * Parse the content of a `<boolean>` element.
 *
 * @remarks
 * Real XML-RPC tooling writes and expects a strict `1`/`0`, and not
 * the `true`/`false` which `xs:boolean` and the rest of this module use.
 *
 * @param cursor - to read from
 * @returns parsed boolean, or an error
 */
function parseBooleanContent(
  cursor: XmlCursor
): AasCommon.Either<AasTypes.JsonValue, DeserializationError> {
  // NOTE (mristin):
  // `whiteSpace` is fixed to `collapse` for every atomic XSD type but
  // a string, so a pretty-printed `<boolean>` has to be read as well.
  const text = collapseWhitespace(parseTextContent(cursor));

  if (text === "1") {
    return new AasCommon.Either<AasTypes.JsonValue, DeserializationError>(
      true, null
    );
  }
  if (text === "0") {
    return new AasCommon.Either<AasTypes.JsonValue, DeserializationError>(
      false, null
    );
  }

  return newDeserializationError<AasTypes.JsonValue>(
    `Expected '0' or '1' as the text of a 'boolean' element, ` +
      `but got: '${text}'`
  );
}

/**
 * Parse the content of a `<double>` element.
 *
 * @param cursor - to read from
 * @returns parsed number, or an error
 */
function parseDoubleContent(
  cursor: XmlCursor
): AasCommon.Either<AasTypes.JsonValue, DeserializationError> {
  // NOTE (mristin):
  // See the note in `parseBooleanContent` on why the whitespace is
  // collapsed here.
  const text = collapseWhitespace(parseTextContent(cursor));

  // NOTE (mristin):
  // The lexical form is matched before the text is converted. `Number`
  // reads far more than we admit here: a hexadecimal literal, so "0x10"
  // would come out as 16, an empty text, which would come out as 0, and
  // the spellings "Infinity" and "-Infinity".
  //
  // Mind that the numeral excludes "INF", "-INF" and "NaN" on purpose,
  // unlike `xs:double`, which names all three. A `<double>` carries
  // a JSON number, and JSON knows neither an infinity nor a not-a-number,
  // so there is no JSON-able value for such a text to parse into.
  if (!DOUBLE_RE.test(text)) {
    return newDeserializationError<AasTypes.JsonValue>(
      `Expected a number as the text of a 'double' element, ` +
        `but got: '${text}'`
    );
  }

  const value = Number(text);

  // NOTE (mristin):
  // A literal too large for a `number` gives an infinity, which is no
  // JSON-able value either, so it is refused rather than rounded.
  if (!Number.isFinite(value)) {
    return newDeserializationError<AasTypes.JsonValue>(
      `Expected a number representable as a JSON-able value as the text ` +
        `of a 'double' element, but got a value which rounds to ` +
        `an infinity: '${text}'`
    );
  }

  return new AasCommon.Either<AasTypes.JsonValue, DeserializationError>(
    value, null
  );
}

