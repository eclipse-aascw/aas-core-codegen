/**
 * Parse the content of a `<data>` element as the items of a JSON-able array.
 *
 * @remarks
 * The `<data>` element is a step of the path, as we enter it, and so is
 * the position of an item. The item's own `<value>` element is not: the index
 * already names it, so a step of its own would say nothing more.
 *
 * @param cursor - to read from
 * @returns parsed JSON-able array, or an error
 */
function parseDataContent(
  cursor: XmlCursor
): AasCommon.Either<AasTypes.JsonArray, DeserializationError> {
  const items = new Array<AasTypes.JsonValue>();

  // eslint-disable-next-line no-constant-condition
  while (true) {
    cursor.skipIgnorable();
    const token = cursor.current();
    if (token === null || !(token instanceof OpenTagToken)) {
      break;
    }

    const itemOrError = parseNamedElementInNoNamespace(cursor, "value", parseValueContent);
    if (itemOrError.error !== null) {
      itemOrError.error.path.prepend(new IndexSegment(items.length));
      itemOrError.error.path.prepend(new ElementSegment("data"));
      return new AasCommon.Either<AasTypes.JsonArray, DeserializationError>(
        null, itemOrError.error
      );
    }

    items.push(itemOrError.mustValue());
  }

  return new AasCommon.Either<AasTypes.JsonArray, DeserializationError>(
    items, null
  );
}

