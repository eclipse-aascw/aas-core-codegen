function writeValue(
  parts: Array<string>,
  value: AasTypes.JsonValue,
  undeclareNamespace: boolean
): void {
  const xmlns = undeclareNamespace ? ' xmlns=""' : "";

  if (value === null || value === undefined) {
    throw new SerializationError(
      `Expected a JSON-able value, but got: ${value}`
    );
  }

  switch (typeof value) {
    case "boolean":
      // NOTE (mristin):
      // Real XML-RPC tooling writes and expects a strict `1`/`0`, and not
      // the `true`/`false` which `xs:boolean` and the rest of this module
      // use.
      parts.push(
        value
          ? `<boolean${xmlns}>1</boolean>`
          : `<boolean${xmlns}>0</boolean>`
      );
      return;

    case "number":
      // NOTE (mristin):
      // JSON knows neither an infinity nor a not-a-number, so neither is
      // a JSON-able value, and `parseDoubleContent` refuses to read either
      // back.
      if (!Number.isFinite(value)) {
        throw new SerializationError(
          `Expected a JSON-able value, but got the number ${value}, ` +
          `which is neither finite nor representable in JSON`
        );
      }
      parts.push(`<double${xmlns}>${value}</double>`);
      return;

    case "string":
      parts.push(`<string${xmlns}>${escapeXmlText(value)}</string>`);
      return;

    case "object":
      break;

    default:
      throw new SerializationError(
        `Expected a JSON-able value (a boolean, a number, a string, ` +
          `an array or an object), but got: ${typeof value}`
      );
  }

  if (Array.isArray(value)) {
    parts.push(`<array${xmlns}>`);
    writeArray(parts, value, false);
    parts.push("</array>");
    return;
  }

  parts.push(`<struct${xmlns}>`);
  writeStruct(parts, value as AasTypes.JsonObject, false);
  parts.push("</struct>");
}

