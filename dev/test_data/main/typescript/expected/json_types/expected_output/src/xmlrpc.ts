/**
 * Parse the content of a `<member>` element as a key and a JSON-able value.
 *
 * @remarks
 * From the `<name>` element on the key is known, so every failure beneath it
 * can name the member it belongs to. A `<struct>` carries that key in a `<name>`
 * child element instead of in an attribute, so the key segment renders as
 * a predicate on that child element, and the `<member>` element itself gets no
 * step of its own.
 *
 * @param cursor - to read from
 * @returns the member's name and its parsed value, or an error
 */
function parseMemberContent(
  cursor: XmlCursor
): AasCommon.Either<[string, AasTypes.JsonValue], DeserializationError> {
  const keyOrError = parseNamedElementInNoNamespace(cursor, "name", parseNameContent);
  if (keyOrError.error !== null) {
    return new AasCommon.Either<
      [string, AasTypes.JsonValue], DeserializationError
    >(null, keyOrError.error);
  }
  const key = keyOrError.mustValue();

  const valueOrError = parseNamedElementInNoNamespace(cursor, "value", parseValueContent);
  if (valueOrError.error !== null) {
    valueOrError.error.path.prepend(new ElementSegment("value"));
    valueOrError.error.path.prepend(new KeySegment(key));
    return new AasCommon.Either<
      [string, AasTypes.JsonValue], DeserializationError
    >(null, valueOrError.error);
  }

  return new AasCommon.Either<
    [string, AasTypes.JsonValue], DeserializationError
  >([key, valueOrError.mustValue()], null);
}

