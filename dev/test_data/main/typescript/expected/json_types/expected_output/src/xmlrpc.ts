function writeArray(
  parts: Array<string>,
  value: AasTypes.JsonArray,
  undeclareNamespace: boolean
): void {
  parts.push(undeclareNamespace ? '<data xmlns="">' : "<data>");
  for (let i = 0; i < value.length; i++) {
    parts.push("<value>");
    try {
      writeNestedValueContent(parts, value[i]);
    } catch (error) {
      if (error instanceof SerializationError) {
        error.prependIndex(i);
      }
      throw error;
    }
    parts.push("</value>");
  }
  parts.push("</data>");
}

/**
 * Write `value` as the content of an element holding a JSON-able object.
 *
 * @remarks
 * The content is a `<member>` per key, each holding a `<name>` and a
 * `<value>`.
 *
 * @param parts - to write to
 * @param value - to be serialized
 * @throws {@link SerializationError} if `value` is not JSON-able
 */
export function writeStructBody(
  parts: Array<string>,
  value: AasTypes.JsonObject
): void {
  writeStruct(parts, value, true);
}

function writeStruct(
  parts: Array<string>,
  value: AasTypes.JsonObject,
  undeclareNamespace: boolean
): void {
  // NOTE (mristin):
  // The members are siblings, so each of them is an outermost element of
  // its own where the enclosing element is not ours.
  const memberStartTag = (
    undeclareNamespace ? '<member xmlns="">' : "<member>"
  );

  for (const key of Object.keys(value)) {
    parts.push(memberStartTag);
    parts.push(`<name>${escapeXmlText(key)}</name>`);
    parts.push("<value>");
    try {
      writeNestedValueContent(parts, value[key]);
    } catch (error) {
      if (error instanceof SerializationError) {
        error.prependKey(key);
      }
      throw error;
    }
    parts.push("</value>");
    parts.push("</member>");
  }
}

