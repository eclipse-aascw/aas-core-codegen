/**
 * Parse the content of an element holding a JSON-able object.
 *
 * @remarks
 * The content is a `<member>` per key, each holding a `<name>` and
 * a `<value>`.
 *
 * @param cursor - to read from
 * @returns parsed JSON-able object, or an error
 */
export function parseStructBody(
  cursor: XmlCursor
): AasCommon.Either<AasTypes.JsonObject, DeserializationError> {
  const members: AasTypes.JsonObject = {};

  // eslint-disable-next-line no-constant-condition
  while (true) {
    cursor.skipIgnorable();
    const token = cursor.current();
    if (token === null || !(token instanceof OpenTagToken)) {
      break;
    }

    const memberOrError = parseNamedElementInNoNamespace(
      cursor, "member", parseMemberContent
    );
    if (memberOrError.error !== null) {
      return new AasCommon.Either<AasTypes.JsonObject, DeserializationError>(
        null, memberOrError.error
      );
    }

    const [key, value] = memberOrError.mustValue();

    // NOTE (mristin):
    // A repeated member name is refused, just as a repeated property element
    // is refused in the de/serialization of the model. Letting the later
    // member win would silently accept a document which says two different
    // things about the same key.
    if (Object.prototype.hasOwnProperty.call(members, key)) {
      const error = new DeserializationError(
        "The member occurred more than once"
      );
      error.path.prepend(new KeySegment(key));
      return new AasCommon.Either<AasTypes.JsonObject, DeserializationError>(
        null, error
      );
    }

    members[key] = value;
  }

  return new AasCommon.Either<AasTypes.JsonObject, DeserializationError>(
    members, null
  );
}

