#: Match the lexical space of ``xs:long``.
#:
#: Mind the explicit ``[0-9]``: ``\d`` would match a digit of any script.
#:
#: See: https://www.w3.org/TR/xmlschema-2/#long
_XS_LONG_RE = re.compile(r"(\+|-)?[0-9]+")


def _read_int_from_element_text(
    element: Element,
    iterator: Iterator[Tuple[str, Element]]
) -> int:
    """
    Parse the text of :paramref:`element` as an integer, and
    read the corresponding end element from :paramref:`iterator`.

    :param element: start element
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :raise:
        :py:class:`DeserializationException` if unexpected input, including
        a value outside of the 64-bit range of ``xs:long``
    :return: parsed value
    """
    text = collapse_whitespace(
        read_text_from_element(
            element,
            iterator
        )
    )

    # NOTE (mristin):
    # ``int`` is far too permissive to be handed the text directly: it takes
    # a digit group separator as in ``1_0``, surrounding whitespace, and
    # a digit of any script -- the Arabic-Indic ``۵`` would be read as 5.
    # Mind that it is checked with ``fullmatch`` and not with ``match``: ``$``
    # would also match just before a trailing newline.
    #
    # See: https://www.w3.org/TR/xmlschema-2/#long
    if _XS_LONG_RE.fullmatch(text) is None:
        raise DeserializationException(
            f"Expected a value as xs:long, "
            f"but got an element with text: {text!r}"
        )

    # NOTE (mristin):
    # We count the significant digits before we call ``int``. The conversion is
    # quadratic in the length of the text, and Python refuses a text of more than
    # 4300 digits, leading zeros included, although ``xs:long`` allows arbitrarily
    # many leading zeros. The largest magnitude, 2^63, has 19 digits.
    digits = text.lstrip("+-").lstrip("0")
    if len(digits) > 19:
        raise DeserializationException(
            f"Expected a value as xs:long, "
            f"but got an element with text out of its range: {text!r}"
        )

    value = int(digits) if len(digits) > 0 else 0
    if text[0] == "-":
        value = -value

    # NOTE (mristin):
    # An ``int`` is unbounded in Python, while ``xs:long`` is a 64-bit integer,
    # so the range has to be checked explicitly, as a number of 19 digits might
    # still not fit. Every other target gets this for free from a parser which
    # refuses what does not fit.
    if value < -9223372036854775808 or value > 9223372036854775807:
        raise DeserializationException(
            f"Expected a value as xs:long, "
            f"but got an element with text out of its range: {text!r}"
        )

    return value


def _read_enum_from_element_text(
    element: Element,
    iterator: Iterator[Tuple[str, Element]],
    literal_from_str: Callable[[str], Optional[_ValueT]],
    enum_name: str
) -> _ValueT:
    """
    Parse the text of :paramref:`element` as an enumeration literal, and read
    the corresponding end element from :paramref:`iterator`.

    :param element: start element
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :param literal_from_str: to parse the literal from its string representation
    :param enum_name: name of the enumeration, for the error messages
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed literal
    """
    text = read_text_from_element(
        element,
        iterator
    )

    literal = literal_from_str(text)
    if literal is None:
        raise DeserializationException(
            f"Not a valid string representation of "
            f"a literal of {enum_name}: {text}"
        )

    return literal


