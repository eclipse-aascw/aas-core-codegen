def _write_something_as_element(
    name: str,
    prop_name: Optional[str],
    that: our_types.Something,
    serializer: '_Serializer'
) -> None:
    """
    Write :paramref:`that` enclosed in the :paramref:`name` element.

    :param name: of the element tag. Expected to contain no XML special characters.
    :param prop_name:
        name of the property, as spelled in Python, whose value is written, or
        ``None`` if the access to the value is recorded by an enclosing writer
    :param that: instance to be serialized
    :param serializer: to write to
    :raise: :py:class:`SerializationException` if the value could not be written
    """
    try:
        serializer.writer.write_start_element(name)
        _write_str_as_element('text', 'text', that.text, serializer)
        _write_int_as_element('number', 'number', that.number, serializer)
        _write_bool_as_element('flag', 'flag', that.flag, serializer)
        _write_enum_as_element('kind', 'kind', that.kind, serializer)
        _write_str_as_element('code', 'code', that.code, serializer)
        _write_item_as_element('item', 'item', that.item, serializer)
        _write_nested_element('parent', 'parent', that.parent, serializer)
        _write_list_of_instances('parents', 'parents', that.parents, serializer)
        _write_list_of_items(
            'texts', 'texts', that.texts, _write_str_as_element, serializer
        )
        if that.optional_text is not None:
            _write_str_as_element(
                'optionalText', 'optional_text', that.optional_text, serializer
            )
        if that.optional_kind is not None:
            _write_enum_as_element(
                'optionalKind', 'optional_kind', that.optional_kind, serializer
            )
        if that.optional_parent is not None:
            _write_nested_element(
                'optionalParent', 'optional_parent', that.optional_parent, serializer
            )
        if that.optional_texts is not None:
            _write_list_of_items(
                'optionalTexts',
                'optional_texts',
                that.optional_texts,
                _write_str_as_element,
                serializer
            )
        if that.optional_data is not None:
            _write_bytes_as_element(
                'optionalData', 'optional_data', that.optional_data, serializer
            )
        if that.optional_member is not None:
            _write_nested_element(
                'optionalMember', 'optional_member', that.optional_member, serializer
            )
        serializer.writer.write_end_element(name)
    except Exception as exception:
        _attribute_to_property(exception, prop_name)


class _Serializer(our_types.AbstractVisitor):
    """Encode instances as XML and write them to :py:attr:`~writer`."""

    #: Frame the XML elements of the document which we are writing
    writer: Final[our_xmlcommon.Writer]

    def __init__(
        self,
        stream: TextIO
    ) -> None:
        """
        Initialize the visitor to write to :paramref:`stream`.

        The first element will include the :py:attr:`~.NAMESPACE`. Every other
        element will not have the namespace specified.

        :param stream: where to write to
        """
        self.writer = our_xmlcommon.Writer(stream)

    def visit_item(
        self,
        that: our_types.Item
    ) -> None:
        """
        Serialize :paramref:`that` to :py:attr:`~stream` as an XML element.

        The enclosing XML element designates the class of the instance, where its
        children correspond to the properties of the instance.

        :param that: instance to be serialized
        """
        _write_item_as_element('item', None, that, self)

    def visit_child_a(
        self,
        that: our_types.ChildA
    ) -> None:
        """
        Serialize :paramref:`that` to :py:attr:`~stream` as an XML element.

        The enclosing XML element designates the class of the instance, where its
        children correspond to the properties of the instance.

        :param that: instance to be serialized
        """
        _write_child_a_as_element('childA', None, that, self)

    def visit_child_b(
        self,
        that: our_types.ChildB
    ) -> None:
        """
        Serialize :paramref:`that` to :py:attr:`~stream` as an XML element.

        The enclosing XML element designates the class of the instance, where its
        children correspond to the properties of the instance.

        :param that: instance to be serialized
        """
        _write_child_b_as_element('childB', None, that, self)

    def visit_something(
        self,
        that: our_types.Something
    ) -> None:
        """
        Serialize :paramref:`that` to :py:attr:`~stream` as an XML element.

        The enclosing XML element designates the class of the instance, where its
        children correspond to the properties of the instance.

        :param that: instance to be serialized
        """
        _write_something_as_element('something', None, that, self)


def write(instance: our_types.Class, stream: TextIO) -> None:
    """
    Write the XML representation of :paramref:`instance` to :paramref:`stream`.

    Example usage:

    .. code-block::

        import pathlib

        import dummy.types as our_types
        import dummy.xmlization as our_xmlization

        instance = Item(
           ... # some constructor arguments
        )

        pth = pathlib.Path(...)
        with pth.open("wt") as fid:
            our_xmlization.write(instance, fid)

    :param instance: to be serialized
    :param stream: to write to
    :raise:
        :py:class:`SerializationException` if :paramref:`instance` could not be
        serialized
    """
    serializer = _Serializer(stream)

    try:
        serializer.visit(instance)
    except Exception as exception:
        _attribute_to_property(exception, None)


def to_str(that: our_types.Class) -> str:
    """
    Serialize :paramref:`that` to an XML-encoded text.

    :param that: instance to be serialized
    :raise:
        :py:class:`SerializationException` if :paramref:`that` could not be
        serialized
    :return: :paramref:`that` serialized to XML serialized to text
    """
    writer = io.StringIO()
    write(that, writer)
    return writer.getvalue()


