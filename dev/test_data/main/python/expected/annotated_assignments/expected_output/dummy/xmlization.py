# NOTE (mristin):
# Directly using the iterator turned out to result in very complex function
# designs. The design became much simpler as soon as we considered one look-ahead
# element. We came up finally with the following pattern which all the protected
# reading functions below roughly follow:
#
# ..code-block::
#
#    _read_*(
#       look-ahead element,
#       iterator
#    ) -> result
#
# The reading functions all read from the ``iterator`` coming from
# :py:func:`xml.etree.ElementTree.iterparse` with the argument
# ``events=["start", "end"]``. The exception :py:class:`.DeserializationException`
# is raised in case of unexpected input.
#
# The reading functions are responsible to read the end element corresponding to the
# start look-ahead element.
#
# When it comes to error reporting, we use exceptions. The exceptions are raised in
# the *callee*, as usual. However, the context of the exception, such as the error path,
# is added in the *caller*, as only the caller knows the context of
# the lookahead-element. In particular, prepending the path segment corresponding to
# the lookahead-element is the responsibility of the *caller*, and not of
# the *callee*.


_ValueT = TypeVar("_ValueT")

#: Read the content of an element which has already been opened, and read
#: the corresponding end element as well
_ContentReader = Callable[
    [Element, Iterator[Tuple[str, Element]]],
    _ValueT
]


def _read_named_element(
    element: Element,
    iterator: Iterator[Tuple[str, Element]],
    expected_tag: str,
    read_content: _ContentReader[_ValueT]
) -> _ValueT:
    """
    Verify that :paramref:`element` bears the :paramref:`expected_tag`, and
    delegate the reading of its content to :paramref:`read_content`.

    This is the only place where an element's tag is checked against the tag which
    its container prescribes -- the XML name of a class, ``<v>`` for a list item, or
    ``<v1>``, ``<v2>``, *etc.* for a tuple item.

    :param element: look-ahead element
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :param expected_tag: expected tag of :paramref:`element`
    :param read_content: to read the content of :paramref:`element`
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed value
    """
    tag_wo_ns = parse_element_tag(element)
    if tag_wo_ns != expected_tag:
        raise DeserializationException(
            f"Expected an element with the tag {expected_tag!r}, "
            f"but got an element with tag: {tag_wo_ns!r}"
        )

    return read_content(element, iterator)


def _read_nested_element(
    element: Element,
    iterator: Iterator[Tuple[str, Element]],
    read_element: _ContentReader[_ValueT],
    expected_what: str
) -> _ValueT:
    """
    Read the instance nested in :paramref:`element` as a discriminator element.

    This looks redundant next to reading a list item, and it is not. A property
    wraps its instance in an element of its own, so the discriminator's name has to
    be prepended to the error path, which then reads ``value/property/idShort``.
    A list item is not wrapped -- the item element *is* the indexed child -- so the
    same prepend would give ``annotations/*[1]/property/idShort``, which walks one
    level past the element that ``*[1]`` already selects, and resolves to nothing.

    The end element corresponding to :paramref:`element` will be read as well.

    :param element: start element enclosing the discriminator element
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :param read_element: to read the nested element, dispatching on its tag
    :param expected_what: name of the expected type, for the error messages
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed instance
    """
    next_event_element = next(iterator, None)
    if next_event_element is None:
        raise DeserializationException(
            f"Expected a discriminator start element corresponding "
            f"to {expected_what}, but got end-of-input"
        )

    next_event, nested_element = next_event_element
    if next_event != 'start':
        raise DeserializationException(
            f"Expected a discriminator start element corresponding "
            f"to {expected_what}, "
            f"but got event {next_event!r} and element {nested_element.tag!r}"
        )

    try:
        result = read_element(nested_element, iterator)
    except DeserializationException as exception:
        exception.path._prepend(ElementSegment(nested_element))
        raise

    read_end_element(element, iterator)

    return result


def _read_dispatched(
    element: Element,
    iterator: Iterator[Tuple[str, Element]],
    dispatch: Mapping[str, _ContentReader[_ValueT]],
    expected_what: str
) -> _ValueT:
    """
    Read the instance of :paramref:`element` by dispatching on its own tag.

    An instance element is self-describing: its tag *is* its model type.

    The end element corresponding to :paramref:`element` will be read as well.

    :param element: start element of the instance
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :param dispatch: to read the instance as a sequence, by its model type
    :param expected_what: what we expected to read, for the error messages
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed instance
    """
    tag_wo_ns = parse_element_tag(element)

    read_as_sequence = dispatch.get(tag_wo_ns)
    if read_as_sequence is None:
        raise DeserializationException(
            f"Expected the element tag to be a valid model type "
            f"of {expected_what}, "
            f"but got tag {tag_wo_ns!r}"
        )

    return read_as_sequence(element, iterator)


def _read_properties(
    element: Element,
    iterator: Iterator[Tuple[str, Element]],
    readers: Mapping[str, _ContentReader[Any]]
) -> Mapping[str, Any]:
    """
    Read the properties of an instance as the children of :paramref:`element`.

    The end element corresponding to :paramref:`element` will be read as well.

    A property may come at most once, and an unknown tag is refused outright.

    The property is marked on the error path here, once for all the properties,
    instead of in every reader: the tag of the child element *is* the XML name of
    the property which we are reading.

    :param element: start element, parent of the properties
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :param readers: to read the content of a property, by its XML name
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed values, by the XML name of the property
    """
    if element.text is not None and len(element.text.strip()) != 0:
        raise DeserializationException(
            f"Expected only XML elements representing the properties "
            f"and whitespace text, but got text: {element.text!r}"
        )

    raise_if_has_tail_or_attrib(element)

    values = {}  # type: Dict[str, Any]

    while True:
        # NOTE (mristin):
        # We pull the next property element here instead of delegating it to
        # a helper. A call is not free in Python, and this loop runs once for
        # every property of every instance.
        next_event_element = next(iterator, None)
        if next_event_element is None:
            raise DeserializationException(
                f"Expected a property element or the end element corresponding "
                f"to {element.tag}, but got the end-of-input"
            )

        next_event, prop_element = next_event_element
        if next_event == 'end' and prop_element.tag == element.tag:
            # We reached the end element enclosing the properties.
            break

        if next_event != 'start':
            raise DeserializationException(
                f"Expected a start element corresponding to a property, "
                f"but got event {next_event!r} "
                f"and element {prop_element.tag!r}"
            )

        try:
            tag_wo_ns = parse_element_tag(prop_element)

            # NOTE (mristin):
            # A tag already in ``values`` can only have got there by being read,
            # so its presence means that the property comes a second time.
            if tag_wo_ns in values:
                raise DeserializationException(
                    f"Property {tag_wo_ns!r} occurred more than once"
                )

            reader = readers.get(tag_wo_ns)
            if reader is None:
                raise DeserializationException(
                    f"Expected an element representing a property, "
                    f"but got an element with unexpected tag: {tag_wo_ns!r}"
                )

            values[tag_wo_ns] = reader(prop_element, iterator)
        except DeserializationException as exception:
            exception.path._prepend(ElementSegment(prop_element))
            raise

    return values


def _read_list_of_items(
    element: Element,
    iterator: Iterator[Tuple[str, Element]],
    read_item: _ContentReader[_ValueT]
) -> List[_ValueT]:
    """
    Read the children of :paramref:`element` as a list of items.

    :paramref:`read_item` is responsible for verifying the tag of each item
    element itself -- *e.g.*, by wrapping a scalar/enumeration reader with
    :py:func:`_read_named_element`, or by relying on a class's own dispatch by
    its natural element tag.

    The end element corresponding to :paramref:`element` will be read as well.

    :param element: start element enclosing the list
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :param read_item: to read a single item, including its own end element
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed items
    """
    if element.text is not None and len(element.text.strip()) != 0:
        raise DeserializationException(
            f"Expected only item elements and whitespace text, "
            f"but got text: {element.text!r}"
        )

    result = []  # type: List[_ValueT]

    while True:
        # NOTE (mristin):
        # We pull the next item element here instead of delegating it to a helper,
        # as this loop runs once for every item of every list.
        next_event_element = next(iterator, None)
        if next_event_element is None:
            raise DeserializationException(
                f"Expected an item element or the end element corresponding "
                f"to {element.tag}, but got the end-of-input"
            )

        next_event, item_element = next_event_element
        if next_event == 'end' and item_element.tag == element.tag:
            # We reached the end element enclosing the items.
            break

        if next_event != 'start':
            raise DeserializationException(
                f"Expected a start element corresponding to an item, "
                f"but got event {next_event!r} "
                f"and element {item_element.tag!r}"
            )

        try:
            item = read_item(item_element, iterator)
        except DeserializationException as exception:
            exception.path._prepend(IndexSegment(item_element, len(result)))
            raise

        result.append(item)

    return result


def _read_instance_from_iterparse(
    iterator: Iterator[Tuple[str, Element]],
    read_as_element: _ContentReader[_ValueT],
    expected_what: str
) -> _ValueT:
    """
    Read an instance from :paramref:`iterator`, starting at its start element.

    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :param read_as_element: to read the instance, including its end element
    :param expected_what: what we expected to read, for the error messages
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed instance
    """
    next_element = read_next_start_element(iterator, expected_what)

    try:
        return read_as_element(next_element, iterator)
    except DeserializationException as exception:
        exception.path._prepend(ElementSegment(next_element))
        raise


def _remove_whitespace(text: str) -> str:
    """
    Drop every whitespace character of :paramref:`text`.

    This is what ``xs:base64Binary`` needs: it allows whitespace between
    the characters and not only around them, so collapsing is not enough.

    :param text: to be stripped of its whitespace
    :return: text without any whitespace
    """
    return XS_WHITESPACE_RE.sub("", text)


_XS_BASE64_CHARACTERS = frozenset(
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "abcdefghijklmnopqrstuvwxyz"
    "0123456789+/"
)

#: Admit the characters which can precede a single ``=``. The two bits which
#: the padding drops have to be zero, which only these sixteen satisfy.
_XS_BASE64_BEFORE_ONE_PAD = frozenset("AEIMQUYcgkosw048")

#: Admit the characters which can precede ``==``, by the same argument over
#: the four bits which are dropped.
_XS_BASE64_BEFORE_TWO_PADS = frozenset("AQgw")


def _matches_xs_base64_binary(text: str) -> bool:
    """
    Tell whether :paramref:`text` is a lexical form of ``xs:base64Binary``.

    The whitespace is expected to be gone already. What is left has to match::

            (B64 B64 B64 B64)* ((B64 B64 B64 B64) | (B64 B64 B16 '=') | (B64 B04 '=='))?

    which is to say: a length which is a multiple of four, the alphabet and
    nothing else, an equals sign only at the very end, and -- easily missed --
    a constrained character *before* the padding, since the bits which
    the padding drops have to be zero.

    The decoders do not agree on any of this. Some take ``SGk`` although it is
    three characters long, some quietly discard a character which is not in
    the alphabet, and some take an equals sign in the middle. Hence the check
    of our own, so that every target refuses the same texts.

    See: https://www.w3.org/TR/xmlschema-2/#base64Binary

    :param text: to be checked, with the whitespace already removed
    :return: True if :paramref:`text` is a lexical form of ``xs:base64Binary``
    """
    if len(text) % 4 != 0:
        return False

    if len(text) == 0:
        return True

    pads = 0
    if text[-1] == "=":
        pads = 1
        if text[-2] == "=":
            pads = 2

    if any(
        character not in _XS_BASE64_CHARACTERS
        for character in text[: len(text) - pads]
    ):
        return False

    if pads == 1:
        return text[-2] in _XS_BASE64_BEFORE_ONE_PAD

    if pads == 2:
        return text[-3] in _XS_BASE64_BEFORE_TWO_PADS

    return True


_XS_BOOLEAN_LITERAL_SET = {
    "1",
    "true",
    "0",
    "false",
}


def _read_bool_from_element_text(
    element: Element,
    iterator: Iterator[Tuple[str, Element]]
) -> bool:
    """
    Parse the text of :paramref:`element` as a boolean, and
    read the corresponding end element from :paramref:`iterator`.

    :param element: start element
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed value
    """
    text = collapse_whitespace(
        read_text_from_element(
            element,
            iterator
        )
    )

    if text not in _XS_BOOLEAN_LITERAL_SET:
        raise DeserializationException(
            f"Expected a boolean, "
            f"but got an element with text: {text!r}"
        )

    return text in ('1', 'true')


#: Match the lexical space of ``xs:long``.
#:
#: Mind the explicit ``[0-9]``: ``\d`` would match a digit of any script.
#:
#: See: https://www.w3.org/TR/xmlschema-2/#long
_XS_LONG_RE = re.compile(r"(\+|-)?[0-9]+")


def _read_int_from_element_text(
    element: Element,
    iterator: Iterator[Tuple[str, Element]]
) -> int:
    """
    Parse the text of :paramref:`element` as an integer, and
    read the corresponding end element from :paramref:`iterator`.

    :param element: start element
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :raise:
        :py:class:`DeserializationException` if unexpected input, including
        a value outside of the 64-bit range of ``xs:long``
    :return: parsed value
    """
    text = collapse_whitespace(
        read_text_from_element(
            element,
            iterator
        )
    )

    # NOTE (mristin):
    # ``int`` is far too permissive to be handed the text directly: it takes
    # a digit group separator as in ``1_0``, surrounding whitespace, and
    # a digit of any script -- the Arabic-Indic ``۵`` would be read as 5.
    # Mind that it is checked with ``fullmatch`` and not with ``match``: ``$``
    # would also match just before a trailing newline.
    #
    # See: https://www.w3.org/TR/xmlschema-2/#long
    if _XS_LONG_RE.fullmatch(text) is None:
        raise DeserializationException(
            f"Expected a value as xs:long, "
            f"but got an element with text: {text!r}"
        )

    # NOTE (mristin):
    # We count the significant digits before we call ``int``. The conversion is
    # quadratic in the length of the text, and Python refuses a text of more than
    # 4300 digits, leading zeros included, although ``xs:long`` allows arbitrarily
    # many leading zeros. The largest magnitude, 2^63, has 19 digits.
    digits = text.lstrip("+-").lstrip("0")
    if len(digits) > 19:
        raise DeserializationException(
            f"Expected a value as xs:long, "
            f"but got an element with text out of its range: {text!r}"
        )

    value = int(digits) if len(digits) > 0 else 0
    if text[0] == "-":
        value = -value

    # NOTE (mristin):
    # An ``int`` is unbounded in Python, while ``xs:long`` is a 64-bit integer,
    # so the range has to be checked explicitly, as a number of 19 digits might
    # still not fit. Every other target gets this for free from a parser which
    # refuses what does not fit.
    if value < -9223372036854775808 or value > 9223372036854775807:
        raise DeserializationException(
            f"Expected a value as xs:long, "
            f"but got an element with text out of its range: {text!r}"
        )

    return value


def _read_bytes_from_element_text(
    element: Element,
    iterator: Iterator[Tuple[str, Element]]
) -> bytes:
    """
    Parse the text of :paramref:`element` as base64-encoded bytes, and
    read the corresponding end element from :paramref:`iterator`.

    :param element: look-ahead element
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed value
    """
    # NOTE (mristin):
    # We do not use ``read_text_from_element`` as that function expects
    # the ``element`` to contain *some* text. An empty ``xs:base64Binary``
    # is a lexical form of its own, and stands for zero bytes -- its whole
    # production is optional -- so it is read here just like an empty
    # ``xs:string`` is.
    raw_text = element.text

    end_element = read_end_element(
        element,
        iterator
    )

    if raw_text is None:
        raw_text = end_element.text

    raise_if_has_tail_or_attrib(element)

    text = _remove_whitespace(
        raw_text
        if raw_text is not None
        else ""
    )

    if not _matches_xs_base64_binary(text):
        raise DeserializationException(
            f"Expected a text as base64-encoded bytes, "
            f"but got an element with text: {text!r}"
        )

    try:
        value = base64.b64decode(text)
    except Exception:
        raise DeserializationException(
            f"Expected a text as base64-encoded bytes, "
            f"but got an element with text: {text!r}"
        ) from None

    return value


def _read_enum_from_element_text(
    element: Element,
    iterator: Iterator[Tuple[str, Element]],
    literal_from_str: Callable[[str], Optional[_ValueT]],
    enum_name: str
) -> _ValueT:
    """
    Parse the text of :paramref:`element` as an enumeration literal, and read
    the corresponding end element from :paramref:`iterator`.

    :param element: start element
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :param literal_from_str: to parse the literal from its string representation
    :param enum_name: name of the enumeration, for the error messages
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed literal
    """
    text = read_text_from_element(
        element,
        iterator
    )

    literal = literal_from_str(text)
    if literal is None:
        raise DeserializationException(
            f"Not a valid string representation of "
            f"a literal of {enum_name}: {text}"
        )

    return literal


