import collections.abc
import math
from typing import Iterator

import dummy.common as aas_common
import dummy.types as aas_types
from dummy.reporting import (
    Error,
    IndexSegment,
    KeySegment
)


def verify_json_value(
    value: aas_types.JsonValue
) -> Iterator[Error]:
    """
    Verify that :paramref:`value` is a JSON-able value, at any depth.

    The path of an error points into :paramref:`value` itself: an item of
    an array contributes an index segment and a member of an object a key
    segment, so that the path leads all the way down to the culprit.

    The value is walked depth first, so an error deep inside the first member
    is reported before an error on the second one. The errors thus come in
    the order in which a reader meets them going through the value.

    :param value: to be verified
    :yield: errors, if any
    """
    # NOTE (mristin):
    # A ``bool`` is an ``int`` in Python, so it has to be checked first --
    # otherwise every boolean would be taken for a number.
    if isinstance(value, bool):
        return

    if isinstance(value, int):
        # NOTE (mristin):
        # JSON knows a single numeric type, so an ``int`` becomes a ``float``
        # on the way out. Only an ``int`` which that conversion can not carry
        # exactly is an error here -- see
        # :py:func:`.common.try_to_convert_int_to_float`.
        if aas_common.try_to_convert_int_to_float(value) is None:
            yield Error(
                f"Expected a JSON-able value, but got the integer {value}, "
                f"which is not exactly representable as a JSON number"
            )

        return

    if isinstance(value, float):
        # NOTE (mristin):
        # JSON knows neither an infinity nor a not-a-number, so neither is
        # a JSON-able value, even though a Python ``float`` is happy to hold
        # either.
        if not math.isfinite(value):
            yield Error(
                f"Expected a JSON-able value, but got the number {value}, "
                f"which is neither finite nor representable in JSON"
            )

        return

    if isinstance(value, str):
        return

    if isinstance(value, (dict, collections.abc.Mapping)):
        for key, item_value in value.items():
            if not isinstance(key, str):
                # NOTE (mristin):
                # There is no key segment to report here: a key which is no
                # string names nothing which the path could descend into, so
                # the path stops at the object which holds it.
                yield Error(
                    f"Expected only string keys in a JSON-able object, but got "
                    f"a key of type: {type(key)}"
                )
                continue

            for error in verify_json_value(item_value):
                error.path._prepend(KeySegment(value, key))
                yield error

        return

    array_like = aas_common.try_to_cast_to_array_like(value)
    if array_like is not None:
        for i, item_value in enumerate(array_like):
            for error in verify_json_value(item_value):
                error.path._prepend(IndexSegment(array_like, i))
                yield error

        return

    yield Error(
        f"Expected a JSON-able value (a boolean, a number, a string, an array "
        f"or an object), but got: {type(value)}"
    )


def verify_json_array(
    value: aas_types.JsonArray
) -> Iterator[Error]:
    """
    Verify that :paramref:`value` is a JSON-able array.

    :param value: to be verified
    :yield: errors, if any
    """
    if aas_common.try_to_cast_to_array_like(value) is None:
        yield Error(
            f"Expected a JSON-able array, but got: {type(value)}"
        )
        return

    yield from verify_json_value(value)


def verify_json_object(
    value: aas_types.JsonObject
) -> Iterator[Error]:
    """
    Verify that :paramref:`value` is a JSON-able object.

    :param value: to be verified
    :yield: errors, if any
    """
    if not isinstance(value, (dict, collections.abc.Mapping)):
        yield Error(
            f"Expected a JSON-able object, but got: {type(value)}"
        )
        return

    yield from verify_json_value(value)
