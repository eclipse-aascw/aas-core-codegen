def write_discriminator(
    value: aas_types.JsonValue,
    writer: Writer
) -> None:
    """
    Write :paramref:`value` as one of the five XML-RPC discriminators.

    :param value: to be serialized
    :param writer: to write to
    :raise: :py:class:`SerializationException` if the value could not be written
    """
    # NOTE (mristin):
    # A ``bool`` is an ``int`` in Python, so it has to be checked first --
    # otherwise every boolean would be written as a number.
    if isinstance(value, bool):
        # NOTE (mristin):
        # Real XML-RPC tooling writes and expects a strict ``1``/``0``, and not
        # the ``true``/``false`` which ``xs:boolean`` and the xmlization use.
        writer.write_start_element_in_no_namespace('boolean')
        writer.stream.write('1' if value else '0')
        writer.write_end_element_in_no_namespace('boolean')
        return

    if isinstance(value, int):
        # NOTE (mristin):
        # An ``int`` is written out as it stands, free of the fraction which
        # a ``float`` carries. JSON knows a single numeric type, though, so
        # it has to be one which a ``float`` can hold exactly -- otherwise
        # a reader, which reads every <double> as a ``float``, would get
        # a different number back.
        if aas_common.try_to_convert_int_to_float(value) is None:
            raise SerializationException(
                f"Expected a JSON-able value, but got the integer {value}, "
                f"which is not exactly representable as a JSON number"
            )

        writer.write_start_element_in_no_namespace('double')
        writer.stream.write(str(value))
        writer.write_end_element_in_no_namespace('double')
        return

    if isinstance(value, float):
        # NOTE (mristin):
        # JSON knows neither an infinity nor a not-a-number, so neither is
        # a JSON-able value, and ``_read_discriminator`` refuses to read
        # either back.
        if not math.isfinite(value):
            raise SerializationException(
                f"Expected a JSON-able value, but got the number {value}, "
                f"which is neither finite nor representable in JSON"
            )

        writer.write_start_element_in_no_namespace('double')

        # NOTE (mristin):
        # ``str`` spells a negative zero as "-0.0", but only if the sign is
        # looked at: ``value == 0`` holds for both zeroes.
        if value == 0 and math.copysign(1.0, value) < 0.0:
            writer.stream.write('-0.0')
        else:
            writer.stream.write(str(value))

        writer.write_end_element_in_no_namespace('double')
        return

    if isinstance(value, str):
        writer.write_start_element_in_no_namespace('string')
        writer.stream.write(
            value.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        )
        writer.write_end_element_in_no_namespace('string')
        return

    if isinstance(value, (dict, collections.abc.Mapping)):
        writer.write_start_element_in_no_namespace('struct')
        write_struct_body(value, writer)
        writer.write_end_element_in_no_namespace('struct')
        return

    array_like = aas_common.try_to_cast_to_array_like(value)
    if array_like is not None:
        writer.write_start_element_in_no_namespace('array')
        write_array_body(array_like, writer)
        writer.write_end_element_in_no_namespace('array')
        return

    raise SerializationException(
        f"Expected a JSON-able value (a boolean, a number, a string, an array "
        f"or an object), but got: {type(value)}"
    )


def write_array_body(
    value: aas_types.JsonArray,
    writer: Writer
) -> None:
    """
    Write the ``<data>`` of the JSON-able array :paramref:`value`.

    The path of a failure points into :paramref:`value`, and not into
    the document, which is only half written when the failure is raised: it is
    the value which the caller holds and can look at.

    :param value: to be serialized
    :param writer: to write to
    :raise: :py:class:`SerializationException` if the value could not be written
    """
    writer.write_start_element_in_no_namespace('data')
    for i, item in enumerate(value):
        writer.write_start_element_in_no_namespace('value')
        try:
            write_discriminator(item, writer)
        except SerializationException as exception:
            exception._prepend_index(i)
            raise
        writer.write_end_element_in_no_namespace('value')
    writer.write_end_element_in_no_namespace('data')


def write_struct_body(
    value: aas_types.JsonObject,
    writer: Writer
) -> None:
    """
    Write the ``<member>``'s of the JSON-able object :paramref:`value`.

    The path of a failure points into :paramref:`value`, and not into
    the document, which is only half written when the failure is raised: it is
    the value which the caller holds and can look at.

    :param value: to be serialized
    :param writer: to write to
    :raise: :py:class:`SerializationException` if the value could not be written
    """
    for key, item in value.items():
        if not isinstance(key, str):
            # NOTE (mristin):
            # A key which is no string names nothing which the path could
            # descend into, so the path stops at the object which holds it.
            raise SerializationException(
                f"Expected only string keys in a JSON-able object, but got "
                f"a key of type: {type(key)}"
            )

        writer.write_start_element_in_no_namespace('member')

        writer.write_start_element_in_no_namespace('name')
        writer.stream.write(
            key.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        )
        writer.write_end_element_in_no_namespace('name')

        writer.write_start_element_in_no_namespace('value')
        try:
            write_discriminator(item, writer)
        except SerializationException as exception:
            exception._prepend_key(key)
            raise
        writer.write_end_element_in_no_namespace('value')

        writer.write_end_element_in_no_namespace('member')


