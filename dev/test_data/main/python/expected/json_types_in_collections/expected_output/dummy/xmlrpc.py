def read_struct_body(
    element: Element,
    iterator: Iterator[Tuple[str, Element]]
) -> aas_types.JsonObject:
    """
    Read the content of :paramref:`element` as a sequence of ``<member>``'s.

    The end element corresponding to :paramref:`element` will be read as well.

    :param element: start element enclosing the members
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: parsed JSON-able object
    """
    raise_if_has_tail_or_attrib(element)

    raise_if_non_whitespace_text(element, '<member> elements')

    result = dict()  # type: Dict[str, Any]

    while True:
        next_event_element = next(iterator, None)
        if next_event_element is None:
            raise DeserializationException(
                f"Expected a <member> element or the end element corresponding "
                f"to {element.tag}, but got the end-of-input"
            )

        next_event, member_element = next_event_element
        if next_event == 'end' and member_element.tag == element.tag:
            break

        if (
            next_event != 'start'
            or parse_unqualified_element_tag(member_element) != 'member'
        ):
            raise DeserializationException(
                f"Expected a start element <member>, but got "
                f"event {next_event!r} and element {member_element.tag!r}"
            )

        key, value = _read_member(member_element, iterator)

        # NOTE (mristin):
        # A repeated <member> name is refused, just as a repeated property
        # element is refused in the xmlization. Letting the later member win
        # would silently accept a document which says two different things
        # about the same key.
        if key in result:
            exception = DeserializationException(
                "The member occurred more than once"
            )
            exception.path._prepend(KeySegment(member_element, key))
            raise exception

        result[key] = value

    return result


def _read_member(
    element: Element,
    iterator: Iterator[Tuple[str, Element]]
) -> Tuple[str, aas_types.JsonValue]:
    """
    Read :paramref:`element`, a ``<member>``, as a key and a JSON-able value.

    The end element corresponding to :paramref:`element` will be read as well.

    :param element: start element of the ``<member>``
    :param iterator:
        Input stream of ``(event, element)`` coming from
        :py:func:`xml.etree.ElementTree.iterparse` with the argument
        ``events=["start", "end"]``
    :raise: :py:class:`DeserializationException` if unexpected input
    :return: the member's name and its parsed value
    """
    raise_if_has_tail_or_attrib(element)

    raise_if_non_whitespace_text(
        element, 'a <name> and a <value> element'
    )

    name_element = read_next_start_element(iterator, 'a <name> element')
    if parse_unqualified_element_tag(name_element) != 'name':
        raise DeserializationException(
            f"Expected a start element <name>, "
            f"but got element {name_element.tag!r}"
        )

    key = read_str_from_element_text(name_element, iterator)

    # NOTE (mristin):
    # From here on the key is known, so every failure can name the member it
    # belongs to. A <struct> carries the key of a member in a <name> child
    # element instead of in an attribute, so the key segment renders as
    # a predicate on that child element, and the <member> element itself gets
    # no step of its own.
    try:
        value_element = read_next_start_element(
            iterator, 'a <value> element'
        )

        try:
            value = read_value_element(value_element, iterator)
        except DeserializationException as exception:
            exception.path._prepend(ElementSegment(value_element))
            raise
    except DeserializationException as exception:
        exception.path._prepend(KeySegment(element, key))
        raise

    read_end_element(element, iterator)

    return key, value


